package ollama

import (
	"context"
	"io"
	"sync"
	"sync/atomic"
	"time"
)

// Сторож молчания на потоке ответа.
//
// **Зачем.** У потокового чтения ответа не было никакого предела. Настройка
// `chat_timeout` ограничивает только ожидание **заголовков** — это
// `ResponseHeaderTimeout` в транспорте, — а сколько молчит уже начавшийся поток,
// не ограничивал никто.
//
// Чем это кончилось, видно в журнале стенда 27.08.2026:
//
//	09:17:57 | 499 | 9h49m44s | 198.51.100.10 | POST "/api/chat"
//
// Запрос с боевого сервера провисел **девять часов сорок девять минут**.
// Он пришёл около 23:28, когда единственный слот `qwen3.8` заняла ночная
// сборка графа, и остался в очереди. Модель `qwen35` параллельных запросов
// не поддерживает, слот у неё один — и пока в очереди висел этот брошенный
// запрос, планировщик Ollama не обслуживал и другие модели. Утром из-за него
// встали эмбеддинги, и карта выглядела свободной, хотя работа стояла.
//
// То есть цена отсутствующего таймаута — не «клиент долго ждёт», а **сервер
// недоступен всем остальным**.
//
// **Почему сторож молчания, а не предел на весь запрос.** Честный длинный
// ответ идёт минутами и всё это время шлёт куски. Оборвать его по общему
// пределу значит сломать нормальную работу. А вот молчание дольше нескольких
// минут — это всегда беда: либо очередь, либо зависший сервер.

// stallReader обрывает чтение, если данных нет дольше отведённого.
//
// Устроен без будильников на каждое чтение: одна горутина смотрит, давно ли
// было последнее чтение, и отменяет запрос. Иначе на каждый кусочек потока
// заводился бы таймер, а кусочков в длинном ответе тысячи.
type stallReader struct {
	rc     io.ReadCloser
	last   atomic.Int64 // время последнего чтения, наносекунды
	cancel context.CancelFunc
	done   chan struct{}
	once   sync.Once // done закрывается ровно один раз, сколько бы ни было Close
}

// newStallReader оборачивает тело ответа. Нулевой предел выключает сторожа.
func newStallReader(rc io.ReadCloser, limit time.Duration, cancel context.CancelFunc) io.ReadCloser {
	if limit <= 0 {
		return rc
	}
	s := &stallReader{rc: rc, cancel: cancel, done: make(chan struct{})}
	s.last.Store(time.Now().UnixNano())

	go func() {
		// Проверяем вчетверо чаще предела: так обрыв случится не позже чем
		// на четверть предела позже срока, и это дешевле точности до секунды.
		tick := limit / 4
		if tick < time.Second {
			tick = time.Second
		}
		t := time.NewTicker(tick)
		defer t.Stop()
		for {
			select {
			case <-s.done:
				return
			case <-t.C:
				quiet := time.Since(time.Unix(0, s.last.Load()))
				if quiet >= limit {
					s.cancel() // отмена контекста рвёт и запрос, и чтение
					return
				}
			}
		}
	}()
	return s
}

func (s *stallReader) Read(p []byte) (int, error) {
	n, err := s.rc.Read(p)
	if n > 0 {
		s.last.Store(time.Now().UnixNano())
	}
	return n, err
}

func (s *stallReader) Close() error {
	// «Проверить и закрыть» двумя действиями — гонка: два одновременных Close
	// закрыли бы канал дважды. sync.Once делает это одним.
	s.once.Do(func() { close(s.done) })
	return s.rc.Close()
}
