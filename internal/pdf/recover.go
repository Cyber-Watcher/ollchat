package pdf

import (
	"errors"
	"fmt"
	"os"
	"runtime/debug"
)

// Защита от аварийного завершения на повреждённых файлах.
//
// Разбор PDF — это чтение чужих данных с прямым обращением по смещениям,
// которые в файле же и записаны. У повреждённого файла смещение может увести
// за границу среза, и тогда обычный выход — паника всей программы. Для
// приложения это значит потерю диалога из-за одного битого файла, а при обходе
// тысяч книг — гарантированную остановку на середине.
//
// Поэтому паника ловится на границе пакета и превращается в обычную ошибку:
// битый документ ничем не отличается от нечитаемого, и обрабатывать его надо
// так же. Стек при этом не теряется: он попадает в текст ошибки, если выставлена
// переменная окружения OLLCHAT_DEBUG.

// ErrDamaged возвращается, когда разбор сорвался на повреждённых данных.
var ErrDamaged = errors.New("документ повреждён: разбор прерван")

// catch превращает панику в ошибку. Вызывается через defer с адресом
// именованного возвращаемого значения.
func catch(what string, err *error) {
	r := recover()
	if r == nil {
		return
	}
	if os.Getenv("OLLCHAT_DEBUG") != "" {
		*err = fmt.Errorf("%w (%s: %v)\n%s", ErrDamaged, what, r, debug.Stack())
		return
	}
	*err = fmt.Errorf("%w (%s: %v)", ErrDamaged, what, r)
}
