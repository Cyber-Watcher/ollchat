package pdf

import "errors"

// Бюджет работы над документом.
//
// Файл в сотни байт умеет потребовать работы без конца: поток FlateDecode
// разжимается в тысячу раз, RunLength после него — ещё в шестьдесят четыре,
// а одна и та же форма или поток содержимого рисуется на каждой из тысяч
// страниц. Каждый поток по отдельности ограничен (maxDecoded), но сумма — нет,
// и до 07.10.2026 такой файл вешал разбор на часы, а при неудаче ронял процесс
// нехваткой памяти, которую recover не ловит.
//
// Поэтому у документа один общий счёт: всё распакованное фильтрами списывается
// с него. Запас щедрый и растёт с размером файла: настоящая книга, даже на
// сотни мегабайт и со сложной графикой, распаковывает в разы меньше, а
// раздутый файл упирается в предел за секунды и получает ErrTooHeavy.
//
// Пределы — переменные, а не константы, только ради тестов: проверять их
// на настоящих величинах значило бы гонять гигабайты в каждом прогоне.
var (
	// maxDecoded ограничивает каждый шаг цепочки фильтров одного потока.
	maxDecoded = 256 << 20

	// workBase и workPerByte задают бюджет документа: workBase плюс
	// workPerByte байт на каждый байт файла.
	workBase    int64 = 1 << 30
	workPerByte int64 = 64
)

// ErrTooHeavy возвращается, когда разбор превысил бюджет работы над
// документом: распакованного в нём больше, чем бывает у настоящих книг.
var ErrTooHeavy = errors.New("документ требует слишком много работы на разбор: " +
	"распакованного в нём несоразмерно больше, чем у настоящих книг, — похоже на повреждённый " +
	"или намеренно раздутый файл")

// budgetFor — бюджет работы над документом из size байт.
func budgetFor(size int) int64 { return workBase + workPerByte*int64(size) }

// spend списывает n байт работы. false — бюджет исчерпан: дальше документ
// не разбирается, а вызывающий получает ErrTooHeavy.
func (d *Document) spend(n int) bool {
	d.work -= int64(n)
	if d.work < 0 {
		d.overspent = true
	}
	return !d.overspent
}

// decodeLimit — сколько байт может выдать один шаг цепочки фильтров. На байт
// больше остатка бюджета: шаг, упёршийся в этот предел, исчерпывает бюджет
// и тем отличается от потока, который просто кончился.
func (d *Document) decodeLimit() int {
	return int(min(int64(maxDecoded), max(d.work, 0)+1))
}
