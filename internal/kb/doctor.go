package kb

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Проверка коллекции: что не так и что с этим делать.
//
// **Зачем.** Тихие потери — худшее, что может случиться с базой знаний: книга
// не прочиталась, скан не дал текста, файл переехал, а поиск просто ничего
// не находит и объяснить это нечем. Доктор превращает молчание в список.
//
// Отчёт живёт здесь, а не в интерфейсе, потому что зовут его двое: команда
// `/kb doctor` в диалоге и ключ `--kb-doctor` в командной строке. Два текста
// об одном разошлись бы в первой же правке — и человек получал бы разные
// ответы на один вопрос в зависимости от того, откуда спросил.

// where печатает книгу двумя строками: каталог, под ним имя файла с отступом.
//
// **Зачем не одной строкой.** Полный путь книги — это полторы сотни знаков,
// и в них тонет то единственное, что человеку нужно: какая книга и где лежит.
// Имя файла отдельной строкой читается сразу, а каталог над ним отвечает
// на вопрос «в каком разделе искать».
//
// Между книгами пустая строка: без неё две пары строк сливаются, и уже
// не видно, какое имя к какому каталогу относится.
func where(b *strings.Builder, path string, paint Painter) {
	dir, file := filepath.Split(path)
	fmt.Fprintf(b, "  %s\n      %s\n\n", strings.TrimSuffix(dir, string(filepath.Separator)), paint.do(file))
}

// Painter выделяет название книги среди сообщений программы.
//
// **Почему цвет приходит снаружи, а не берётся здесь.** Отчёт читают в двух
// местах: в терминале, где цвет — управляющая последовательность ANSI, и в ленте
// диалога, где им распоряжается lipgloss. А ещё его перенаправляют в файл, куда
// управляющие последовательности писать нельзя вовсе. Решение «красить или нет»
// принимает тот, кто знает, куда смотрит человек; здесь известно только, какие
// слова — названия книг.
type Painter func(string) string

// do красит, если красить есть чем. Метод на типе, а не проверка у каждого
// вызова: мест покраски в отчёте восемь, и восемь проверок на nil разошлись бы.
func (p Painter) do(s string) string {
	if p == nil {
		return s
	}
	return p(s)
}

// DoctorOpts — настройки проверки.
//
// Набором, а не четырьмя доводами подряд: `Doctor(coll, true, nil, nil)` не
// читается вовсе, и перепутать в нём местами два nil — дело одной правки.
type DoctorOpts struct {
	// Deep включает сверку книг по содержимому: она читает файлы-кандидаты
	// целиком и потому стоит секунд, а не миллисекунд.
	Deep bool
	// InGraph отвечает, разбирал ли граф куски этой книги. Пусто — про граф
	// ничего не известно, и отчёт о нём молчит, а не выдумывает.
	InGraph InGraph
	// Paint выделяет названия книг. Пусто — отчёт без цвета.
	Paint Painter
	// Step сообщает о ходе долгих шагов: имя шага, сделано, всего.
	// total = 0 означает «сколько всего, заранее неизвестно».
	// Пусто — работать молча.
	Step func(stage string, done, total int)
}

// step вызывает обработчик хода работы, если он задан.
func (o DoctorOpts) step(stage string, done, total int) {
	if o.Step != nil {
		o.Step(stage, done, total)
	}
}

// InGraph отвечает, разбирал ли граф куски этой книги.
//
// Передаётся снаружи, а не берётся здесь: граф зависит от базы знаний,
// и обратная зависимость замкнула бы круг.
type InGraph func(docID uint32) bool

// Doctor собирает отчёт о состоянии коллекции.
//
// Долгих шагов здесь два — проверка файлов на месте и сверка по содержимому, —
// и оба сообщают о себе через o.Step: на живой библиотеке проверка идёт секунды,
// и молчащая программа неотличима от зависшей.
func Doctor(c *Collection, o DoctorOpts) string {
	deep, inGraph, paint := o.Deep, o.InGraph, o.Paint
	// Помеченные удалёнными не показываем: человек их уже убрал, и видеть
	// их снова в списке неполадок — значит решать, что работа не сделалась.
	books := c.LiveBooks()
	st := c.Stats()

	var gone, scans, broken []BookRec
	byTitle := map[string][]BookRec{}
	o.step("проверяю книги на месте", 0, len(books))
	for i, b := range books {
		o.step("проверяю книги на месте", i+1, len(books))
		// **Наличие файла проверяется у книги любого вида.** Прежде проверялись
		// только успешно прочитанные, и удалённый с диска скан оставался
		// в отчёте сканом: человек убрал книгу, а доктор продолжал показывать
		// её среди «сканов без текста» и молчал о том, что файла нет.
		// Поймано 30.08.2026 на живой библиотеке.
		if _, err := os.Stat(b.Path); err != nil {
			gone = append(gone, b)
			continue
		}
		switch b.Kind {
		case BookOK:
			byTitle[normalizeTitle(b.Title)] = append(byTitle[normalizeTitle(b.Title)], b)
		case BookScan:
			scans = append(scans, b)
		case BookBroken, BookGarbled, BookSkipped:
			broken = append(broken, b)
		}
	}

	var b strings.Builder

	if len(gone) > 0 {
		// **Это не то же самое, что «помечено удалёнными».** Здесь книги,
		// про которые коллекция ещё не знает, что их нет: файл исчез, а запись
		// цела, и поиск по ним по-прежнему работает. Помеченные ниже — уже
		// разобранный случай. Два числа в одном отчёте без этой оговорки
		// читаются как противоречие.
		fmt.Fprintf(&b, "\nПропали с диска, но ещё числятся в коллекции: %d\n", len(gone))
		for i, r := range gone {
			if i >= 5 {
				fmt.Fprintf(&b, "  …и ещё %d\n\n", len(gone)-5)
				break
			}
			where(&b, r.Path, paint)
		}
		b.WriteString("  Поиск по ним пока работает: текст лежит в коллекции, а не в файле.\n" +
			"  Пометить их удалёнными — команда в конце отчёта.\n")
	}
	// **Диск против реестра, а не только реестр против диска.**
	//
	// Доктор проверял лишь одну сторону: на месте ли книги, о которых он знает.
	// Обратный случай — книгу положили в каталог, а проиндексировать забыли —
	// он не видел вовсе и отвечал «всё в порядке». Это худший вид молчания:
	// человек уверен, что книга в базе, поиск её не находит, и объяснить это
	// нечем. Замер 30.08.2026: владелец добавил книги, запустил проверку
	// и не услышал о них ни слова.
	//
	// Файлы не читаются — сверка идёт по размеру и времени, как в `--kb-sync`.
	o.step("ищу новые книги в каталогах", 0, 0)
	pend, perr := c.Pending()
	var pendFiles []string
	if perr == nil {
		pendFiles = pend.Files
	}
	if len(pendFiles) > 0 {
		fmt.Fprintf(&b, "\nЛежат в каталогах, но в индексе их нет: %d\n", len(pendFiles))
		// Список целиком: его сверяют глазами с тем, что клали в каталог.
		for _, f := range pendFiles {
			where(&b, f, paint)
		}
		b.WriteString("  Поиск их не находит вовсе.\n")
	}

	// Изменившиеся после индексации — отдельно от новых. Поиск по ним работает
	// и отдаёт прежний текст, а это хуже, чем не находить: ответ со ссылкой
	// на строку, которой больше нет. Правка без изменения размера (этап 92)
	// показывается особо — именно она однажды уехала мимо индекса молча.
	if perr == nil && len(pend.Changed) > 0 {
		same := 0
		for _, ch := range pend.Changed {
			if ch.SameSize {
				same++
			}
		}
		fmt.Fprintf(&b, "\nИзменились на диске после индексации: %d\n", len(pend.Changed))
		for i, ch := range pend.Changed {
			if i >= 5 {
				fmt.Fprintf(&b, "  …и ещё %d\n\n", len(pend.Changed)-5)
				break
			}
			where(&b, ch.Path, paint)
			if ch.SameSize {
				b.WriteString("      размер тот же, новее только время: правка на месте\n")
			}
		}
		b.WriteString("  Поиск по ним отдаёт ПРЕЖНИЙ текст — ссылки на строки могут вести\n" +
			"  в никуда. Перечитать: команда в конце отчёта.\n")
		if same > 0 {
			fmt.Fprintf(&b, "  Из них %d с тем же размером: такие правки индекс сам не замечал (этап 92).\n", same)
		}
	}

	// Копии уже проиндексированных книг.
	//
	// **Отдельным разделом, а не вместе с новыми.** Индексация их намеренно
	// пропускает, поэтому совет «долить» на них не действует: выполнив его,
	// человек возвращается к проверке и видит ровно тот же список. Замер
	// 30.08.2026 — именно так и вышло, дважды подряд. Лечится удалением копии
	// с диска, а файлов программа не удаляет никогда.
	if len(pend.Dupes) > 0 {
		fmt.Fprintf(&b, "\nЛежат в каталогах копиями: %d — те же файлы уже в индексе\n",
			len(pend.Dupes))
		b.WriteString("  Индексация их пропускает намеренно, и доливка тут не поможет:\n" +
			"  книга уже есть, просто под другим именем.\n\n")
		var wasted int64
		for _, d := range pend.Dupes {
			wasted += d.Size
			// Не через where: там книга закрывается пустой строкой, а здесь
			// под именем идёт ещё строка «то же, что», и пустая посреди пары
			// разрывает то, что читается только вместе.
			dir, file := filepath.Split(d.Path)
			fmt.Fprintf(&b, "  %s\n      %s\n      то же, что: %s\n\n",
				strings.TrimSuffix(dir, string(filepath.Separator)),
				paint.do(file), paint.do(filepath.Base(d.Same)))
		}
		fmt.Fprintf(&b, "  Занимают на диске: %.1f МБ. Убрать — удалить копию файла;\n"+
			"  индекс при этом не меняется, книга остаётся в нём под первым именем.\n",
			float64(wasted)/1e6)
	}

	if perr != nil {
		// Молчать нельзя: не сумев обойти каталоги, доктор не знает про новые
		// книги ничего — а промолчав, выдаёт незнание за «их нет».
		fmt.Fprintf(&b, "\nКаталоги с книгами не обошлись (%s):\n"+
			"  про новые и изменившиеся книги сказать нечего. Обычная причина —\n"+
			"  внешний диск не подключён.\n", perr)
	}

	if len(scans) > 0 {
		fmt.Fprintf(&b, "\nСканы без текстового слоя: %d\n", len(scans))
		for i, r := range scans {
			if i >= 3 {
				break
			}
			where(&b, r.Path, paint)
		}
		b.WriteString("  Текста в них нет; страницы можно показать модели с vision через /addimg.\n")
	}
	if len(broken) > 0 {
		fmt.Fprintf(&b, "\nНе прочитались: %d\n", len(broken))
		for i, r := range broken {
			if i >= 5 {
				fmt.Fprintf(&b, "  …и ещё %d\n\n", len(broken)-5)
				break
			}
			dir, file := filepath.Split(r.Path)
			fmt.Fprintf(&b, "  %s\n      %s\n      причина: %s\n\n",
				strings.TrimSuffix(dir, string(filepath.Separator)), paint.do(file), r.Err)
		}
	}

	// Побайтово одинаковые книги под разными именами.
	//
	// **Это худший вид дубля, и по названию он не ловится.** Копию почти всегда
	// переименовывают, и «разные издания» её не находят. А вред от неё прямой:
	// две одинаковые выдержки занимают два места из восьми в выдаче, вытесняя
	// другие книги; правило «не больше трёх кусков из одной книги» не спасает,
	// потому что книги формально разные.
	same := 0
	if deep {
		var wasted int
		for _, grp := range sameContent(books, o.step) {
			if same == 0 {
				b.WriteString("\nОдна и та же книга под разными именами:\n")
			}
			same++
			for i := range grp[1:] {
				wasted += grp[i+1].Chunks
			}
			if same <= 5 {
				where(&b, grp[0].Path, paint)
				for _, r := range grp[1:] {
					fmt.Fprintf(&b, "      то же, что: %s\n", paint.do(filepath.Base(r.Path)))
					fmt.Fprintf(&b, "      убрать:  ollchat --kb-forget %s %q\n\n", c.Name(), r.Path)
				}
			}
		}
		if same > 5 {
			fmt.Fprintf(&b, "  …и ещё %d\n", same-5)
		}
		if same > 0 {
			fmt.Fprintf(&b, "  Лишних кусков: %d. Убирать — командой выше; файл на диске она не трогает.\n", wasted)
		}
	}

	// Разные издания одной книги: выдача от них страдает меньше (тексты
	// всё-таки различаются), но место занимают вдвойне.
	dups := 0
	titles := make([]string, 0, len(byTitle))
	for t := range byTitle {
		titles = append(titles, t)
	}
	sort.Strings(titles) // порядок отчёта не должен зависеть от карты
	for _, title := range titles {
		group := byTitle[title]
		if title == "" || len(group) < 2 {
			continue
		}
		if dups == 0 {
			b.WriteString("\nПохоже на разные издания одной книги:\n")
		}
		if dups < 5 {
			fmt.Fprintf(&b, "  %s — %d экземпляра\n", paint.do(group[0].Title), len(group))
		}
		dups++
	}
	if dups > 5 {
		fmt.Fprintf(&b, "  …и ещё %d\n", dups-5)
	}

	if st.Segments > 6 {
		// **Без обещания ускорить поиск.** Замер 30.08.2026 на копии живой
		// библиотеки: 18 сегментов — 28.37 мс на запрос, тот же корпус,
		// уплотнённый в один сегмент, — 28.68 мс. Разницы нет. Прежний текст
		// («каждый добавляет свой проход») звучал как названная цена, а цены
		// этой никто не измерял.
		fmt.Fprintf(&b, "\nСегментов %d. На скорости поиска это не сказывается "+
			"(замерено), но каждый\n  занимает место — уплотнение сливает их в один.\n",
			st.Segments)
	}
	// Помеченные удалёнными: со списком, а не числом.
	//
	// «Помечено удалёнными: 15» человеку ничего не говорит: то ли это его
	// вчерашняя работа, то ли что-то пропало само. Список отвечает сразу.
	del := c.DeletedBooks()
	if len(del) > 0 {
		fmt.Fprintf(&b, "\nУже помечены удалёнными: %d — из выдачи ушли, но их текст остался в индексе коллекции.\n"+
			"  Это уже сделанная работа, а не новая беда. Речь не о файлах книг:\n"+
			"  коллекция хранит текст у себя, и он лежит в ней до уплотнения —\n"+
			"  даже когда самой книги на диске давно нет.\n\n", len(del))
		// **Список целиком, без «и ещё N».** Его читают глазами, сверяя
		// с тем, что человек удалял сам; обрезанный список для этого негоден.
		//
		// Пустая строка над списком обязательна: без неё пояснение сверху
		// и первая книга стоят вплотную, и глаз читает их как одно —
		// а это разные вещи, объяснение и перечень.
		//
		// Метка [в графе] важнее, чем кажется: у разобранной графом книги
		// остаются понятия и связи, опирающиеся на её куски, — не поломка,
		// но знать об этом надо. У неразобранной следов не остаётся вовсе.
		//
		// «Разобрана» — состояние, а не незаконченное дело: граф собирается
		// каталогами, и книга либо попала в один из проходов, либо нет.
		inG := 0
		for _, r := range del {
			mark := ""
			if inGraph != nil && inGraph(r.ID) {
				mark, inG = "[в графе] ", inG+1
			}
			fmt.Fprintf(&b, "  %s%s\n", mark, paint.do(filepath.Base(r.Path)))
		}
		if inGraph == nil {
			b.WriteString("\n  Графа нет или он не открылся — про следы в нём сказать нечего.\n")
		} else if inG > 0 {
			fmt.Fprintf(&b, "\n  Из них графом разобрано: %d. Понятия и связи из них в графе остались;\n"+
				"  чтобы убрать и их, граф придётся собрать заново.\n", inG)
		} else {
			// Пустая строка перед выводом: он относится ко всему списку выше,
			// а не к последней его строке, и слитно читается как приписка
			// к последней книге.
			b.WriteString("\n  Ни для одной из них граф не посчитан.\n")
		}
	}
	if st.Stale {
		fmt.Fprintf(&b, "\nПравила разбора изменились (%s → %s): стоит пересобрать коллекцию.\n",
			st.Analyzer, AnalyzerVersion)
	}
	if len(gone)+len(scans)+len(broken)+dups+same+len(pendFiles)+len(pend.Dupes) == 0 &&
		!st.Stale && len(del) == 0 {
		b.WriteString("\nВсё в порядке: непрочитанных, пропавших, сканов, сбоев и повторов нет.\n")
	}

	// **Что сделать — отдельным разделом в конце.**
	//
	// Отчёт без вывода заставляет человека самому соображать, какая команда
	// к какой находке относится, — а он пришёл с вопросом «что не так»,
	// а не «изучить устройство базы». Советы собраны в порядке выполнения:
	// сперва привести реестр в согласие с диском, потом уплотнить.
	var todo []string
	if len(pendFiles) > 0 || len(pend.Changed) > 0 {
		// Первым делом: остальные советы говорят, как убрать лишнее, а этот —
		// как добавить недостающее, и он единственный меняет выдачу к лучшему.
		// `--kb-refresh`, а не `--kb-sync`: доливка без счёта смыслов оставит
		// новые книги невидимыми для смыслового поиска, и он об этом смолчит.
		// Изменившиеся перечитываются той же командой: доливка берёт всё,
		// у чего размер или время разошлись с записью.
		var what []string
		if len(pendFiles) > 0 {
			what = append(what, "прочитать "+booksAcc(len(pendFiles)))
		}
		if len(pend.Changed) > 0 {
			what = append(what, fmt.Sprintf("перечитать %d изменивш%s", len(pend.Changed),
				map[bool]string{true: "уюся", false: "ихся"}[len(pend.Changed) == 1]))
		}
		todo = append(todo, fmt.Sprintf(
			"ollchat --kb-refresh %s   — %s и сразу посчитать смыслы",
			c.Name(), strings.Join(what, ", ")))
	}
	if len(gone) > 0 {
		todo = append(todo, fmt.Sprintf(
			"ollchat --kb-sync %s   — пометить %s; из выдачи они уйдут сразу",
			c.Name(), booksWord(len(gone))))
	}
	if len(del) > 0 || st.Segments > 6 {
		line := fmt.Sprintf("ollchat --kb-merge %s   — уплотнить: выбросить удалённое", c.Name())
		if st.Segments > 6 {
			line += fmt.Sprintf(" и слить %d сегментов в один", st.Segments)
		}
		if c.HasGraph() {
			line += "\n      ВНИМАНИЕ: по коллекции собран граф — уплотнение сменит нумерацию кусков,\n" +
				"      и граф придётся собирать заново (десятки часов). Обход: --kb-merge-force"
		}
		todo = append(todo, line)
	}
	if st.Stale {
		todo = append(todo, fmt.Sprintf(
			"ollchat --kb-reindex %s <путь>   — перечитать книги новыми правилами разбора", c.Name()))
	}
	if len(todo) > 0 {
		b.WriteString("\nЧто сделать:\n")
		for _, t := range todo {
			fmt.Fprintf(&b, "  %s\n", t)
		}
	}

	// Сводка вперёд, подробности следом.
	//
	// **Зачем.** Отчёт по живой библиотеке — это сотня строк, а вопрос к нему
	// обычно один: «всё ли в порядке». Читать сотню строк ради ответа «да»
	// неразумно, и до сих пор это обходили строкой `grep` по заголовкам
	// разделов — способ, который ломается молча: заголовок переименовали,
	// `grep` перестал находить раздел и показал «чисто» там, где чисто не было
	// (я сам переименовал два заголовка 30.08.2026, за один день).
	//
	// Поэтому сводку даёт программа. Считается она по тем же числам, из которых
	// собраны разделы, — разойтись им негде.
	var head strings.Builder
	fmt.Fprintf(&head, "Проверка коллекции %s\n", c.Name())
	sum := summary{
		unindexed: len(pendFiles),
		copies:    len(pend.Dupes),
		gone:      len(gone),
		scans:     len(scans),
		broken:    len(broken),
		sameFiles: same,
		editions:  dups,
		deleted:   len(del),
		segments:  st.Segments,
		stale:     st.Stale,
	}
	head.WriteString(sum.String())
	return strings.TrimRight(head.String()+b.String(), "\n")
}

// SameContent находит группы книг с одинаковым содержимым.
//
// Сначала по размеру, потом побайтово: сравнивать отпечатки всех книг подряд
// значило бы перечитывать всю библиотеку — сотни мегабайт ради ответа, который
// в девяноста девяти случаях из ста «повторов нет». Совпадение размера — сито,
// пропускающее единицы.
//
// В группе первой идёт книга с меньшим номером: она проиндексирована раньше,
// и на неё больше ссылок в графе, поэтому оставлять правильно её.
func SameContent(books []BookRec) [][]BookRec { return sameContent(books, nil) }

// sameContent — то же самое, но с докладом о ходе работы.
//
// Доклад нужен потому, что этот шаг — самый долгий в проверке: он читает
// книги-кандидаты целиком. Считается не по книгам библиотеки, а по кандидатам,
// прошедшим сито размера: их единицы, и «3 из 6» честнее, чем «12 из 900».
func sameContent(books []BookRec, step func(string, int, int)) [][]BookRec {
	bySize := map[int64][]BookRec{}
	for _, b := range books {
		if b.Kind == BookOK {
			bySize[b.Size] = append(bySize[b.Size], b)
		}
	}
	total := 0
	for _, grp := range bySize {
		if len(grp) > 1 {
			total += len(grp)
		}
	}
	done := 0
	if step != nil {
		step("сверяю книги по содержимому", 0, total)
	}

	var out [][]BookRec
	for _, grp := range bySize {
		if len(grp) < 2 {
			continue
		}
		byHash := map[string][]BookRec{}
		for _, b := range grp {
			if step != nil {
				done++
				step("сверяю книги по содержимому", done, total)
			}
			h, err := fileHash(b.Path)
			if err != nil {
				continue // пропавший файл — забота другого раздела отчёта
			}
			byHash[h] = append(byHash[h], b)
		}
		for _, same := range byHash {
			if len(same) < 2 {
				continue
			}
			sort.Slice(same, func(i, j int) bool { return same[i].ID < same[j].ID })
			out = append(out, same)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i][0].Path < out[j][0].Path })
	return out
}

// normalizeTitle приводит заголовок к виду, по которому узнаются разные издания
// одной книги: без регистра, без года издания и знаков препинания.
//
// **Цифры сохраняются, и это главное.** Первая редакция выбрасывала их все —
// и объявляла одной книгой то, что различается ровно цифрой (замер 30.08.2026
// на живой библиотеке):
//
//	«Using and Administering Linux Volume 1 / 2 / 3» — три разных тома;
//	«Tools and Skills for .NET 8» и «для .NET 10»   — разные книги;
//	«C# 12 and .NET 8» и «C# 13 and .NET 9»          — разные издания разных лет.
//
// Ложное срабатывание здесь дороже пропуска: человек, поверив отчёту, удалит
// второй том книги, которую читает.
//
// Год издания убирается: он и правда лишний — «Docker Deep Dive 2023»
// и «Docker Deep Dive 2025» стоит показать рядом. Убирается только отдельно
// стоящее четырёхзначное число, похожее на год, а не любая цифра.
func normalizeTitle(s string) string {
	var out []rune
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= 'а' && r <= 'я', r >= '0' && r <= '9', r == ' ':
			out = append(out, r)
		default:
			out = append(out, ' ') // знак препинания — граница слова, а не склейка
		}
	}
	words := strings.Fields(string(out))
	kept := words[:0]
	for _, w := range words {
		if isYear(w) {
			continue
		}
		kept = append(kept, w)
	}
	return strings.Join(kept, " ")
}

// booksAcc склоняет «прочитать N книг» — винительный падеж.
//
// Отдельно от booksWord («5 пропавших книг», родительный) и от одноимённого
// помощника командной строки («к разбору 1 книга», именительный): падежи разные,
// и один помощник на три места давал бы неверную речь в двух из них.
func booksAcc(n int) string {
	word := "книг"
	switch {
	case n%10 == 1 && n%100 != 11:
		word = "книгу"
	case n%10 >= 2 && n%10 <= 4 && (n%100 < 12 || n%100 > 14):
		word = "книги"
	}
	return fmt.Sprintf("%d %s", n, word)
}

// booksWord склоняет «пропавшая книга»: отчёт читает человек, а не программа.
func booksWord(n int) string {
	switch {
	case n%10 == 1 && n%100 != 11:
		return fmt.Sprintf("%d пропавшую книгу", n)
	case n%10 >= 2 && n%10 <= 4 && (n%100 < 10 || n%100 >= 20):
		return fmt.Sprintf("%d пропавшие книги", n)
	default:
		return fmt.Sprintf("%d пропавших книг", n)
	}
}

// isYear узнаёт год издания: четыре цифры, начинающиеся с 19 или 20.
func isYear(w string) bool {
	if len(w) != 4 {
		return false
	}
	for _, r := range w {
		if r < '0' || r > '9' {
			return false
		}
	}
	return strings.HasPrefix(w, "19") || strings.HasPrefix(w, "20")
}

// summary — сводка отчёта: что нашлось, одной строкой на находку.
//
// Отдельным типом, а не печатью по месту: сводка обязана перечислять ровно то,
// что перечисляют разделы ниже. Собранная из тех же чисел в одном месте, она
// не может разойтись с ними при следующей правке.
type summary struct {
	unindexed int
	copies    int
	gone      int
	scans     int
	broken    int
	sameFiles int
	editions  int
	deleted   int
	segments  int
	stale     bool
}

// String собирает сводку. Пусто — если говорить не о чем.
//
// Порядок строк — по важности для выдачи, а не по порядку разделов: непрочитанная
// книга не находится вовсе, и это хуже, чем лишний сегмент или старая пометка.
func (s summary) String() string {
	type row struct {
		n    int
		text string
	}
	rows := []row{
		{s.unindexed, "не в индексе — поиск их не находит"},
		{s.copies, "копии на диске — индексация их пропускает"},
		{s.gone, "пропали с диска, но ещё в выдаче"},
		{s.broken, "не прочитались"},
		{s.scans, "сканы без текста"},
		{s.sameFiles, "одна книга под разными именами"},
		{s.editions, "похожи на разные издания"},
		{s.deleted, "помечены удалёнными (место на диске)"},
	}
	var b strings.Builder
	for _, r := range rows {
		if r.n > 0 {
			fmt.Fprintf(&b, "  %4d  %s\n", r.n, r.text)
		}
	}
	// Сегменты и устаревшие правила — не про книги, поэтому отдельной строкой
	// и без числа книг: смешать их со списком выше значило бы соврать счётом.
	if s.segments > 6 {
		fmt.Fprintf(&b, "  %4d  сегментов — на поиск не влияет, занимают место\n", s.segments)
	}
	if s.stale {
		b.WriteString("        правила разбора изменились — стоит перечитать книги\n")
	}
	if b.Len() == 0 {
		return ""
	}
	return "\nКоротко (подробности ниже, команды в конце):\n" + b.String()
}
