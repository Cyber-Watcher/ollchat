package kb

import "testing"

// TestFuseRRF — два вида одного документа (этап 112, С9): кусок, найденный обоими,
// поднимается; список обрезается до want; при равенстве — по ссылке.
func TestFuseRRF(t *testing.T) {
	a := []Result{{ID: "b/1#1"}, {ID: "b/1#2"}, {ID: "b/1#3"}}
	b := []Result{{ID: "b/9#9"}, {ID: "b/1#3"}}
	got := FuseRRF(a, b, 20, 3)
	if len(got) != 3 {
		t.Fatalf("длина %d, ждали 3", len(got))
	}
	// b/1#3: 1/23 + 1/22 — больше, чем у первых мест каждого списка (1/21).
	if got[0].ID != "b/1#3" {
		t.Fatalf("первым %s, ждали кусок из обоих видов b/1#3: %+v", got[0].ID, got)
	}
	// b/1#1 и b/9#9 — по 1/21, ничья решается ссылкой.
	if got[1].ID != "b/1#1" || got[2].ID != "b/9#9" {
		t.Fatalf("порядок %v, ждали b/1#1, b/9#9 следом", []string{got[1].ID, got[2].ID})
	}
}
