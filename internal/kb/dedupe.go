package kb

// Отбрасывание почти одинаковых кусков из выдачи (этап 105, Ж4).
//
// **Откуда взялось.** «Transformers and Large Language Models» (2026, стр. 241)
// советует мерить попарную близость отобранных кусков и выбрасывать те, что
// повторяют уже оставленные: место в выдаче дорого, а два почти одинаковых
// куска стоят как два и отвечают как один.
//
// **Почему это нужно именно нам.** Куски нарезаются С ПЕРЕКРЫТИЕМ, и соседние
// куски одной книги делят по нескольку предложений. На графе это уже стоило
// нам искажения: 16 % подтверждений связей оказались копиями одного
// предложения из соседних кусков (`overlap-inflates-confirmations`). В выдаче
// та же природа: вопрос попадает в середину абзаца, и первые два-три места
// занимают три соседних куска с одним и тем же текстом.
//
// **Мера — та же, что у смыслового поиска.** Косинус между квантованными
// векторами кусков (`Cosine`), уже посчитанными и лежащими на диске: модель
// не зовётся, карта не нужна. У кусков без векторов близость неизвестна,
// и они остаются как есть — молча выбрасывать то, чего не измерил, нельзя.

// DedupeSimilar убирает из списка куски, слишком похожие на те, что уже
// оставлены выше. Возвращает отфильтрованный список и число выброшенных.
//
// Порядок входного списка — это ранжирование, и он сохраняется: из пары
// похожих остаётся тот, кто стоял выше. Куски из разных книг сравниваются
// так же, как из одной: дословный повтор через две книги — такой же повтор
// (обе книги остаются в выдаче, если говорят разное).
//
// minCos ≤ 0 выключает проверку целиком: выключатель нужен, чтобы мерить
// «до/после» одним бинарём.
func (c *Collection) DedupeSimilar(hits []Result, minCos float64) ([]Result, int) {
	if minCos <= 0 || len(hits) < 2 {
		return hits, 0
	}
	c.mu.RLock()
	vecs := c.vectors
	c.mu.RUnlock()
	if vecs == nil || vecs.Count() == 0 {
		return hits, 0
	}

	out := make([]Result, 0, len(hits))
	kept := make([][]int8, 0, len(hits))
	dropped := 0
	for _, h := range hits {
		v := vectorOf(vecs, h.Chunk)
		if v == nil {
			out = append(out, h) // близость неизвестна — оставляем
			continue
		}
		dup := false
		for _, k := range kept {
			if Cosine(v, k) >= minCos {
				dup = true
				break
			}
		}
		if dup {
			dropped++
			continue
		}
		out = append(out, h)
		kept = append(kept, v)
	}
	return out, dropped
}

// vectorOf — вектор куска или nil, если его нет. Векторы считаются начальным
// отрезком (куски дописываются в конец), поэтому у свежих книг вектора может
// не быть вовсе, пока не прошёл счёт.
func vectorOf(v *Vectors, chunk int) []int8 {
	if chunk < 0 || chunk >= v.Count() {
		return nil
	}
	return v.At(chunk)
}
