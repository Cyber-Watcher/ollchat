package kb

import "fmt"

// Пределы «тощей» книги: текст извлёкся, но его слишком мало для такого файла.
//
// **Зачем это нужно.** 23.09.2026 в библиотеку попали две книги, каждая из
// которых прошла все прежние проверки и оказалась бесполезной:
//
//   - «N8N Intelligence» — 67.1 МБ, внутри 371 JPG (каждая страница — картинка)
//     и 372 файла разметки на 179 КБ, то есть обёртки к этим картинкам.
//     Текста извлеклось на 7 кусков. Проба на скан её не поймала: текст
//     в разметке есть, просто он не содержание книги, а подписи.
//   - «Building Resilient Distributed Systems» (Сэм Ньюмен) — 8.7 МБ, 31 файл
//     разметки по ~1.5 КБ: заголовок главы и первый абзац, дальше глоссарий.
//     Это превью издательства, а не книга; 65 кусков на 16 глав.
//
// Обе попали в индекс, обе выдавались в поиске обрывками и обе были удалены
// человеком руками. Проверка ловит их ДО записи кусков (слово владельца
// 24.09.2026: «чтобы они даже в индекс не попадали»).
//
// **Пороги выбраны замером, а не на глаз** (24.09.2026, 559 настоящих книг
// коллекции books плюс эти две):
//
//	признак                       ложных   поймано
//	кусков/МБ < 1.0                    0    N8N (0.10/МБ)
//	кусков < 100 и файл > 3 МБ         0    N8N и Ньюмен (7 и 65 кусков)
//	кусков < 150 и файл > 3 МБ         2    — порог отвергнут
//
// Ближайшая настоящая книга к порогу по кускам — «Vector Databases for
// Enterprise AI», 116 кусков на 3.4 МБ; по плотности — «CompTIA Linux+ XK0-005
// Cert Guide», 4.45 куска на МБ (900 страниц вёрстки с картинками). Запас
// до порогов — 16% и 4.5 раза соответственно.
//
// Маленькая книга сама по себе подозрительной не считается: предел по числу
// кусков действует только на файлы крупнее MinMB. Статья на 40 страниц
// и 60 кусков — обычное дело, и трогать её незачем.
type ThinLimits struct {
	// MinChunks — меньше этого числа кусков у файла крупнее MinMB значит
	// «текста нет, есть только обложка». 0 — умолчание, -1 — не проверять.
	MinChunks int

	// MinMB — с какого размера файла работает предел по числу кусков.
	// 0 — умолчание.
	MinMB int

	// ChunksPerMB — плотность текста: меньше этого числа кусков на мегабайт
	// значит «страницы-картинки». 0 — умолчание, -1 — не проверять.
	ChunksPerMB float64
}

// Умолчания пределов. Вынесены в постоянные, а не зашиты в проверку:
// их видно из конфига, и замер, который их выбрал, описан выше.
const (
	DefaultThinMinChunks   = 100
	DefaultThinMinMB       = 3
	DefaultThinChunksPerMB = 1.0
)

// resolve подставляет умолчания. Отдельным шагом, чтобы проверка не решала
// дважды одно и то же и чтобы тесты могли смотреть на итоговые числа.
func (l ThinLimits) resolve() ThinLimits {
	if l.MinChunks == 0 {
		l.MinChunks = DefaultThinMinChunks
	}
	if l.MinMB == 0 {
		l.MinMB = DefaultThinMinMB
	}
	if l.ChunksPerMB == 0 {
		l.ChunksPerMB = DefaultThinChunksPerMB
	}
	return l
}

// Verdict решает, тощая ли книга, и объясняет причину человеку.
//
// Пустая причина значит «книга в порядке». Причина написана так, чтобы
// человек мог проверить решение сам: в ней стоят и числа книги, и порог.
func (l ThinLimits) Verdict(chunks int, size int64) (bool, string) {
	lim := l.resolve()
	if size <= 0 || chunks <= 0 {
		return false, "" // пустую книгу ловит проверка на скан, не эта
	}
	mb := float64(size) / (1 << 20)
	if lim.ChunksPerMB > 0 && mb >= 1 && float64(chunks)/mb < lim.ChunksPerMB {
		return true, fmt.Sprintf(
			"текста почти нет: %d кусков на %.1f МБ (%.2f на МБ, порог %.2f) — похоже на страницы-картинки",
			chunks, mb, float64(chunks)/mb, lim.ChunksPerMB)
	}
	if lim.MinChunks > 0 && chunks < lim.MinChunks && mb > float64(lim.MinMB) {
		return true, fmt.Sprintf(
			"мало текста для такого файла: %d кусков (порог %d) при размере %.1f МБ — похоже на превью издательства",
			chunks, lim.MinChunks, mb)
	}
	return false, ""
}
