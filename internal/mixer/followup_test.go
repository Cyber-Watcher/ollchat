package mixer

import "testing"

// У9: правило продолжения — то же, что `is_followup` в evalpair.py.
func TestIsFollowup(t *testing.T) {
	for _, tc := range []struct {
		text string
		want bool
	}{
		{"а как настроить сбор логов с сервера?", true},            // зачин «а», 7 слов
		{"И что с безопасностью при таком подходе в целом?", true}, // «И» с большой
		{"а, понял, а как тогда быть с доступом извне?", true},     // «а,» со знаком
		{"то есть всё это работает без отдельного сервера?", true},
		{"что насчёт кеширования ответов на стороне клиента?", true},
		{"Что насчет кеширования ответов на стороне клиента?", true},
		{"а дальше?", true},     // коротко
		{"Покажи пример", true}, // коротко — продолжение по длине
		{"ананас растёт на дереве или нет, расскажи подробно", false},
		{"Какие функции OpenCV используются для аффинных преобразований изображения?", false},
		{"то естьвот так слитно написано и длинно очень", false},
		{"   ", false},
	} {
		if got := IsFollowup(tc.text); got != tc.want {
			t.Errorf("IsFollowup(%q) = %v, ждали %v", tc.text, got, tc.want)
		}
	}
}

// Склейка — как в наборе kb_followups_concat.toml: «вопрос реплика» через пробел;
// не продолжение или нет прошлого вопроса — реплика как есть.
func TestFollowupQuery(t *testing.T) {
	prev := "Хочу мониторить сервер Ubuntu через Grafana."
	if got := FollowupQuery(prev, "а как настроить сбор логов с сервера?"); got !=
		"Хочу мониторить сервер Ubuntu через Grafana. а как настроить сбор логов с сервера?" {
		t.Errorf("склейка: %q", got)
	}
	long := "Какие функции OpenCV используются для аффинных преобразований изображения?"
	if got := FollowupQuery(prev, long); got != long {
		t.Errorf("смена темы склеена: %q", got)
	}
	if got := FollowupQuery("", "а дальше?"); got != "а дальше?" {
		t.Errorf("без прошлого вопроса: %q", got)
	}
}
