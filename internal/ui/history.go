package ui

import "strings"

// История введённого: перебор прошлых вопросов стрелками, как в оболочке.
//
// Зачем. Вопрос ушёл — и оказалось, что сервер недоступен, модель без vision
// или в вопросе опечатка. Набирать заново длинный вопрос, который только что
// был набран, обидно, а выделять его мышью из ленты и вставлять обратно —
// работа не для человека.
//
// Почему в памяти, а не файлом. Решение владельца 24.08.2026: история живёт
// один запуск. Файл потребовал бы предела длины, разведения одновременных
// экземпляров (их у владельца несколько — ssh и окна tmux) и ответа на вопрос,
// что делать с вопросами, содержащими личное. Ничего из этого не нужно, чтобы
// вернуть вопрос, отправленный минуту назад.
//
// Хранится всё набранное: вопросы, слэш-команды и отклонённые вопросы.
// Отклонённые — важнее прочего: ради них всё и делается. Поэтому запись идёт
// в момент отправки, до всех проверок, а не после успешного ответа.
type inputHistory struct {
	items []string

	// idx — куда смотрим. Значение len(items) означает «в истории не листаем,
	// набираем новое»; отдельного признака нет намеренно, иначе он разъедется
	// с idx.
	idx int

	// draft — то, что было набрано до захода в историю. Возврат вниз до конца
	// обязан вернуть именно его, а не пустое поле: набранное — тоже работа.
	draft string
}

// maxHistory — предел длины. Взято с запасом: столько вопросов за один запуск
// не задают, а расти без предела не должно ничто.
const maxHistory = 500

// add запоминает набранное и выводит перебор в исходное положение.
func (h *inputHistory) add(s string) {
	defer func() { h.idx, h.draft = len(h.items), "" }()

	if strings.TrimSpace(s) == "" {
		return
	}
	// Два одинаковых вопроса подряд — одна запись: иначе перебор буксует
	// на повторе там, где человек жал Enter дважды.
	if n := len(h.items); n > 0 && h.items[n-1] == s {
		return
	}
	h.items = append(h.items, s)
	if len(h.items) > maxHistory {
		h.items = append([]string(nil), h.items[len(h.items)-maxHistory:]...)
	}
}

// back — шаг к более раннему вопросу. Второе значение: было ли куда шагать.
//
// current передаётся, а не берётся из поля, потому что история о поле ввода
// ничего не знает — так её можно проверить без запуска интерфейса.
func (h *inputHistory) back(current string) (string, bool) {
	if h.idx == 0 || len(h.items) == 0 {
		return "", false
	}
	if h.idx == len(h.items) {
		h.draft = current
	}
	h.idx--
	return h.items[h.idx], true
}

// forward — шаг к более позднему. Дойдя до конца, возвращает набранное
// до захода в историю.
func (h *inputHistory) forward() (string, bool) {
	if h.idx >= len(h.items) {
		return "", false
	}
	h.idx++
	if h.idx == len(h.items) {
		return h.draft, true
	}
	return h.items[h.idx], true
}

// len — сколько записей. Нужен строке состояния и проверкам.
func (h *inputHistory) len() int { return len(h.items) }

// atInputTop — курсор на самой верхней видимой строке поля ввода.
//
// Считается по строкам на экране, а не по логическим: длинный вопрос без
// переводов строки лежит в одной логической строке, но занимает на экране
// три. Если смотреть только на логические, стрелка вверх со второй экранной
// строки уводила бы в историю вместо движения курсора.
func (m *Model) atInputTop() bool {
	return m.ta.Line() == 0 && m.ta.LineInfo().RowOffset == 0
}

// atInputBottom — курсор на самой нижней видимой строке поля ввода.
func (m *Model) atInputBottom() bool {
	info := m.ta.LineInfo()
	return m.ta.Line() == m.ta.LineCount()-1 && info.RowOffset == info.Height-1
}

// setInput кладёт в поле ввода текст из истории.
//
// Курсор в конец: перебрав вопрос, чаще всего дописывают или правят хвост,
// а не начало. Списки под полем пересобираются, потому что текст сменился
// целиком — иначе список файлов остался бы от прежнего «@…».
func (m *Model) setInput(text string) {
	m.ta.SetValue(text)
	m.ta.CursorEnd()
	m.syncFileMenu()
	m.syncPendingImages()
	m.syncPastes()
}
