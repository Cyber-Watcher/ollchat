package ui

import (
	"context"
	"fmt"
	"time"

	tea "charm.land/bubbletea/v2"

	"github.com/Cyber-Watcher/ollchat/internal/ollama"
)

// Ожидание загрузки модели в память карты.
//
// **Что происходит и почему это выглядит поломкой.** Ollama держит модель
// в памяти ограниченное время и выгружает её. Первый вопрос после запуска
// (или после долгого перерыва) заставляет сервер прочитать веса с диска
// и перенести их в видеопамять. На модели в семьдесят миллиардов параметров
// это десятки секунд, и всё это время `/api/chat` не отдаёт ни куска ответа.
//
// Со стороны разницы с зависанием нет никакой: нажал Enter — и тишина.
// Человек делает единственное разумное в такой ситуации — жмёт Ctrl+C, то есть
// отменяет загрузку. Следующий вопрос начинает её заново, и так по кругу.
//
// Лечится это не ускорением, а словом: программа спрашивает сервер, что у него
// загружено, и пока модели там нет — пишет «загружается», а не «думает».

// genStartup — поколение проверки, сделанной не ради конкретного вопроса.
//
// **Почему проверять надо на старте, а не при отправке.** Сам запрос к серверу
// идёт доли секунды, но эти доли складываются с тем, что и так выглядит
// зависанием: человек нажал Enter, и первые три-четыре секунды не менялось
// ничего — ни слова, ни счётчика. Замер владельца 30.08.2026: «поздно
// сработало». К моменту первого вопроса ответ должен уже лежать в памяти
// программы, а проверка при отправке — только уточнение.
const genStartup = -1

// residencyMsg — ответ сервера о том, где лежит модель.
type residencyMsg struct {
	// gen — поколение запуска, ради которого спрашивали. genStartup означает
	// «спросили заранее, вне обмена»: такой ответ годится всегда.
	gen int
	res ollama.Residency
}

// checkResidency спрашивает сервер, загружена ли модель.
//
// Отдельной командой, а не перед отправкой: спрашивать синхронно значит
// задержать сам вопрос на время сетевого запроса — ради подсказки, без которой
// можно обойтись. Ответ приходит через доли секунды и застаёт обмен в самом
// начале, когда он и нужен.
func checkResidency(gen int, client *ollama.Client, model string) tea.Cmd {
	if client == nil || model == "" {
		return nil
	}
	return func() tea.Msg {
		// Свой короткий срок: подсказка, опоздавшая на минуту, бесполезна,
		// а держать запрос на общем таймауте чата (десятки минут) незачем.
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		return residencyMsg{gen: gen, res: client.Resident(ctx, model)}
	}
}

// hintDelay — сколько ждать, прежде чем объяснять человеку, что происходит.
//
// **Почему не сразу.** Ответ сервера о том, что модели нет в памяти, приходит
// за доли секунды, а сама загрузка бывает и быстрой: маленькая модель встаёт
// за пару секунд, и объяснение на полстроки успевает только замусорить ленту.
// Объяснять надо тогда, когда ожидание уже стало заметным, — а строка состояния
// говорит «загружается» с первой секунды, и её достаточно.
//
// Четыре секунды: столько человек ещё ждёт спокойно, а дальше начинает гадать.
const hintDelay = 4 * time.Second

// hintTimerMsg — пора ли объяснять, что происходит.
type hintTimerMsg struct{ gen int }

// loadHintAfter заводит отложенное объяснение.
func loadHintAfter(gen int) tea.Cmd {
	return tea.Tick(hintDelay, func(time.Time) tea.Msg { return hintTimerMsg{gen: gen} })
}

// loadingStatus — что писать в строке состояния вместо «думает…».
//
// Пусто означает «писать обычное»: модель на месте, или ответ уже пошёл,
// или сервер не ответил и выдумывать нечего.
func (m *Model) loadingStatus(now time.Time) string {
	// Пошли куски ответа — модель уже отвечает, чем бы она ни была занята
	// до этого. Это вернее любого опроса сервера.
	if m.gotOutput || !m.streaming {
		return ""
	}
	if !m.residency.Known || m.residency.Loaded {
		return ""
	}
	// Время показывается с первой секунды: неподвижная надпись сама по себе
	// читается как зависание, а растущий счётчик — нет.
	return fmt.Sprintf("загружается в память карты… %s",
		humanWait(now.Sub(m.startedAt)))
}

// startupHint — что сказать при запуске, если модели нет в памяти сервера.
//
// Короче, чем loadingHint: человек ещё не ждёт, он только сел работать.
// Задача этой строки — не объяснить происходящее, а снять будущее недоумение
// заранее, до того как оно возникнет.
func startupHint(model string) string {
	return "Модели " + model + " сейчас нет в памяти сервера. Первый вопрос будет ждать, " +
		"пока Ollama прочитает её веса с диска и перенесёт в видеопамять: " +
		"на больших моделях это десятки секунд. Ответа всё это время не будет — " +
		"это не зависание."
}

// loadingHint — что сказать в ленте, один раз за обмен.
func loadingHint(model string) string {
	return "Модели " + model + " нет в памяти сервера — Ollama сейчас читает её веса " +
		"с диска и переносит в видеопамять. На больших моделях это десятки секунд, " +
		"и всё это время ответа не будет. Программа не зависла; Esc прервёт ожидание, " +
		"но следующий вопрос начнёт загрузку заново."
}

// humanWait печатает ожидание так, как его читает человек.
func humanWait(d time.Duration) string {
	s := int(d.Seconds())
	if s < 60 {
		return fmt.Sprintf("%d с", s)
	}
	return fmt.Sprintf("%d мин %02d с", s/60, s%60)
}
