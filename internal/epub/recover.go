package epub

import (
	"errors"
	"fmt"
	"os"
	"runtime/debug"
)

// Защита от аварийного завершения на повреждённых книгах.
//
// Книга — это ZIP с разметкой внутри, и обе части приходят извне. Битый архив
// или обрезанная глава не должны ронять приложение вместе с диалогом, а при
// обходе тысяч книг — останавливать всю работу. Поэтому паника ловится на
// границе пакета и превращается в обычную ошибку. Подробности — в таком же
// файле пакета pdf.

// ErrDamaged возвращается, когда разбор сорвался на повреждённых данных.
var ErrDamaged = errors.New("книга повреждена: разбор прерван")

// catch превращает панику в ошибку. Вызывается через defer с адресом
// именованного возвращаемого значения.
func catch(what string, err *error) {
	r := recover()
	if r == nil {
		return
	}
	if os.Getenv("OLLCHAT_DEBUG") != "" {
		*err = fmt.Errorf("%w (%s: %v)\n%s", ErrDamaged, what, r, debug.Stack())
		return
	}
	*err = fmt.Errorf("%w (%s: %v)", ErrDamaged, what, r)
}
