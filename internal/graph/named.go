package graph

// Именованные графы: несколько графов над одной коллекцией книг.
//
// **Зачем.** Граф стоит недель работы видеокарты, и проверять на нём опыты —
// значит рисковать сделанным. Опыт (другая схема извлечения, другой промпт,
// связывание новых сущностей при сборке) требует новой сборки, но не требует
// новых книг: коллекция общая, дублировать её незачем — ни 120 МБ кусков,
// ни векторы 464 767 кусков, которые считались часами карты.
//
// Раскладка каталогов:
//
//	<коллекция>/graph        рабочий граф   (kind = production)
//	<коллекция>/graph-lab    опытный граф   (kind = experimental)
//
// **Умолчание не меняется.** Пустое имя — прежний каталог `graph`, поэтому
// собранное раньше читается прежним кодом без единой правки на диске.

import (
	"regexp"
)

// Kind — назначение графа: по нему доктор решает, ругаться ли на неполноту.
type Kind string

const (
	// KindProduction — рабочий граф. За его здоровьем следят.
	KindProduction Kind = "production"
	// KindExperimental — опытный граф. Он заведомо неполон, и сторож на него
	// не срабатывает: сторож, кричащий не по делу, перестаёт читаться.
	KindExperimental Kind = "experimental"
)

// Норм имени графа: оно становится частью пути, поэтому ни пробелов, ни точек,
// ни косых. Пустое имя — рабочий граф в каталоге `graph`.
var nameOK = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,31}$`)

// ValidName проверяет имя графа. Пустое имя допустимо: это граф по умолчанию.
func ValidName(name string) bool { return name == "" || nameOK.MatchString(name) }

// DirFor отдаёт имя подкаталога графа внутри каталога коллекции.
func DirFor(name string) string {
	if name == "" {
		return DirName
	}
	return DirName + "-" + name
}
