package graph

import (
	"fmt"
	"path/filepath"
)

// Rules — правила одного открытого графа: какой подкаталог, как входить
// по слову и по смыслу, как показывать связи, действуют ли группы и склейки.
//
// До этапа 91 (R3) всё это лежало в атомарных переменных пакета, которые
// выставлял config.UseGraph при запуске. Два графа с разными правилами
// в одном процессе были невозможны, а тесты зависели от порядка вызовов.
// Теперь правила — параметр открытия: их несёт сам *Graph, и компилятор
// не даёт открыть граф, не сказав, по каким правилам.
//
// Нулевое значение — рабочий граф с умолчаниями из замеров (см. lexrules.go),
// группы выключены, склейки действуют. Так `Rules{}` годится везде, где
// настроек нет: в тестах, в службах без конфига.
type Rules struct {
	// Name — имя графа: "" — рабочий (каталог graph), иначе graph-<имя>.
	Name string

	// Словесный вход: длина основы и число книг, см. DefaultStemMinLen.
	StemMinLen int
	// SharedAliasLimit — синоним у стольких и более понятий ключом не служит
	// (этап 104, Ж1.7); 0 — умолчание, отрицательное — выключить.
	SharedAliasLimit int
	StemMinBooks     int

	// EntryStopWords — слова, которые сами по себе входом в граф не бывают,
	// см. DefaultEntryStopWords. nil — умолчание; пустой список — правило
	// выключено.
	EntryStopWords []string

	// Смысловой вход и показ связей, см. DefaultSenseTie и соседей.
	SenseTie      float64
	SenseMargin   float64
	VectorAliases int
	MaxEvidences  int

	// Вход по тройкам (этап 105, Б8): TripleLimit — сколько ближайших к вопросу
	// троек «X —тип→ Y» добавлять во вход (их концы становятся понятиями
	// выдачи с пометкой «по связи»); 0 — вход выключен, индекс не читается.
	// TripleMinOrigins — с какого числа источников связь попадает в индекс
	// (0 — DefaultTripleMinOrigins). Индекс считает --graph-embed-edges.
	TripleLimit      int
	TripleMinOrigins int

	// PathFlow — цепочку между понятиями искать по потоку (PathRAG), а не
	// по числу шагов: см. pathByFlow в search.go. Выключатель ради замера
	// «до/после» одним бинарём (этап 105, Б5); умолчание — прежний обход.
	PathFlow bool

	// SeedRelationsOff — НЕ поднимать в выдачу связи между понятиями, которые
	// сами найдены по вопросу (см. promoteSeeds в search.go).
	//
	// **Зачем выключатель.** Правку поиска надо уметь сравнить с прежним
	// поведением на одном бинаре — иначе «до» и «после» считаются разными
	// сборками, и разница в числах может оказаться разницей в способе счёта.
	// Замер 16.09.2026 на 60 парах «как связаны X и Y» так и сделан.
	// В работе всегда false: подъём — не опыт, а исправление.
	SeedRelationsOff bool

	// VectorDesc — класть ли описание понятия (entdesc.jsonl) в текст его
	// вектора, следом за синонимами.
	//
	// **Умолчание «нет», и это не осторожность ради осторожности.** Включение
	// меняет векторы понятий, то есть смысловой вход — а входом пользуются
	// и поиск, и подмешивание к вопросу. Такое меняют по замеру, а не заодно
	// с другой правкой, поэтому ключ отдельный и выключенный.
	//
	// Описания есть только у хабов (262 понятия на 16.09.2026): у остальных
	// поле пусто, и для них ничего не меняется ни при каком значении.
	VectorDesc bool

	// ChainHubLimit — сколько связей у понятия, чтобы считать его «хабом»
	// и не пускать цепочку через него (этап 101, D1).
	//
	// **Замер 08.09.2026** на наборе из 60 пар понятий: без запрета цепочка
	// находилась у 25 пар, и 88% этих цепочек шли через хаб — «ASCII → Go →
	// string literals», «variadic → Go → NumOut», где у Go 11 466 связей.
	// Такая цепочка формально верна и не объясняет ничего. С запретом (500)
	// цепочка находится у 26 пар из 27 — то есть теряется одна, — и средняя
	// длина даже короче: 2.27 шага против 2.44.
	//
	// Концы пути хабами быть могут: их назвал вопрос. Запрет касается только
	// промежуточных узлов. 0 — умолчание (500), отрицательное — не запрещать.
	ChainHubLimit int

	// WeightsByOrigins — вес пары понятий в разбиении тем и в мерах строения
	// считать по ИСТОЧНИКАМ, а не по кускам: соседние куски одной книги —
	// одно подтверждение (этап 101, Г9: 96% таких пар — копия фразы из зоны
	// перекрытия, 16% подтверждений графа books). Замер 10.09.2026: на весах
	// по источникам Louvain перестраивает темы у 20% понятий сильно, при
	// контроле с возмущением на 1% — у 0.4%; крупнейшая тема 6 763 → 5 974.
	// Включается настройкой graph.weights_by_origins; после смены нужен
	// --graph-communities и описания изменившихся тем.
	WeightsByOrigins bool

	// RelatedWeight — множитель веса нетипизированной связи «связано»
	// (RelRelated) в разбиении тем. 0 — умолчание 0.5 (замер Ф1, ниже),
	// 1 — как было до 13.09.2026, отрицательное запрещено валидацией.
	//
	// **Зачем.** «Связано» — это 29.7% всех связей графа и заведомо самый
	// слабый вид: модель не смогла назвать отношение. Замеры этапа 101 (Ф1,
	// 08.09.2026) и повтор на выросшем графе (12.09.2026, 248 168 понятий,
	// 1 531 432 записи) дают одно и то же: при весе 0.5 тем 24 694 против
	// 27 779 на полном весе (−11.1%), медиана размера темы 3 вместо 2,
	// и **ни одно понятие не теряется**. Полное выбрасывание «связано»
	// (вес 0) даёт похожее число тем (24 180), но уносит 48 988 понятий
	// (19.7%) — у них других связей нет. То есть шум мешает разбиению
	// как ВЕС, а не как факт связи, и средний вариант лучше обоих крайних.
	//
	// Само число в графе ничего не меняет до `--graph-communities`:
	// разбиение пересчитывается только этой командой, и после неё нужны
	// описания изменившихся тем (карта).
	RelatedWeight float64

	// Groups — режим групп «про одно»: GroupOff, GroupUnion, GroupExpand.
	// Пусто или незнакомое — off: молчаливо ничего не делать безопаснее,
	// чем гадать.
	Groups string

	// MergesOff выключает действие склеек двойников (настройка
	// merges_enabled = false). Нулевое значение — склейки действуют.
	MergesOff bool

	// Format — версия формата, которой ЗАВОДИТСЯ новый граф (настройка
	// format). Нулевое значение — FormatVersion, то есть рабочий формат 1.
	// На уже собранный граф не действует: его версия записана в паспорте.
	//
	// Формат 2 допустим только у именованного графа: в каталог `graph`
	// рабочего графа он не попадает никогда — решение владельца 04.09.2026,
	// рабочий граф неприкосновенен.
	Format int
}

// DefaultRules — правила рабочего графа с умолчаниями из замеров.
func DefaultRules() Rules { return Rules{}.norm() }

// Normalized — правила с заполненными умолчаниями: то, что действует в графе.
func (r Rules) Normalized() Rules { return r.norm() }

// norm заполняет нули умолчаниями и проверяет режим групп.
func (r Rules) norm() Rules {
	if r.StemMinLen <= 0 {
		r.StemMinLen = DefaultStemMinLen
	}
	switch {
	case r.SharedAliasLimit == 0:
		r.SharedAliasLimit = DefaultSharedAliasLimit
	case r.SharedAliasLimit < 0:
		r.SharedAliasLimit = 0 // выключено
	}
	if r.EntryStopWords == nil {
		r.EntryStopWords = DefaultEntryStopWords
	}
	if r.StemMinBooks <= 0 {
		r.StemMinBooks = DefaultStemMinBooks
	}
	if r.SenseTie <= 0 {
		r.SenseTie = DefaultSenseTie
	}
	if r.SenseMargin <= 0 {
		r.SenseMargin = DefaultSenseMargin
	}
	if r.VectorAliases <= 0 {
		r.VectorAliases = DefaultVectorAliases
	}
	if r.MaxEvidences <= 0 {
		r.MaxEvidences = DefaultMaxEvidences
	}
	if r.TripleMinOrigins <= 0 {
		r.TripleMinOrigins = DefaultTripleMinOrigins
	}
	if r.ChainHubLimit == 0 {
		r.ChainHubLimit = DefaultChainHubLimit
	}
	switch r.Groups {
	case GroupOff, GroupUnion, GroupExpand:
	default:
		r.Groups = GroupOff
	}
	if r.Format <= 0 {
		r.Format = FormatVersion
	}
	return r
}

// Validate проверяет имя графа: строчные латинские буквы, цифры и дефис.
func (r Rules) Validate() error {
	if !ValidName(r.Name) {
		return fmt.Errorf("недопустимое имя графа %q: строчные латинские буквы, цифры и дефис, до 32 знаков", r.Name)
	}
	if r.Format > 0 && !KnownVersion(r.Format) {
		return fmt.Errorf("формат графа %d не поддерживается (известны: %s)", r.Format, versionsHuman())
	}
	if r.Format >= FormatV2 && r.Name == "" {
		return fmt.Errorf("формат %d допустим только у именованного графа (graph.name), "+
			"а не у рабочего в каталоге %s: рабочий граф формата 1 неприкосновенен", r.Format, DirName)
	}
	return nil
}

// RelatedWeightOr — множитель веса «связано» с умолчанием.
//
// 0 значит «не задано» и даёт 0.5: нулевое graph.Rules{} — это рабочий граф
// с умолчаниями из замеров, а не граф без весов.
func (r Rules) RelatedWeightOr() float64 {
	if r.RelatedWeight <= 0 {
		return 0.5
	}
	return r.RelatedWeight
}

// Dir — каталог графа внутри каталога коллекции.
func (r Rules) Dir(collDir string) string { return filepath.Join(collDir, DirFor(r.Name)) }

// Rules отдаёт правила, по которым открыт граф (уже с умолчаниями).
func (g *Graph) Rules() Rules {
	if g == nil {
		return DefaultRules()
	}
	return g.rules
}

// stopSet — слова рамки вопроса в виде множества, в нормализованном
// написании: вопрос нормализуется тем же Normalize перед разбором.
func (r Rules) stopSet() map[string]bool {
	out := make(map[string]bool, len(r.EntryStopWords))
	for _, w := range r.EntryStopWords {
		if w = Normalize(w); w != "" {
			out[w] = true
		}
	}
	return out
}
