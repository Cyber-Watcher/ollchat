package graph

import "strings"

// ExpandQuery дополняет вопрос именами найденных в графе понятий и их
// синонимами — переводит вопрос на язык библиотеки.
//
// **Зачем.** Библиотека двуязычная, а вопрос задают на одном языке. Замер
// 30.08.2026: `/search горутина` возвращал одни русские книги, хотя векторы
// посчитаны для всей коллекции и язык переходят — та же русская фраза внутри
// английской книги («Learn Concurrent Programming with Go») находила ровно
// нужные страницы. Причина не в смысле, а в слиянии списков: русский кусок
// попадает и в словесный список, и в смысловой, и получает награду за согласие
// (RRF), а английский есть только в смысловом. С добавленным `goroutine`
// английский кусок получает тот же второй голос.
//
// Граф здесь работает переводчиком: он знает, что «дообучение» — это
// fine-tuning, а «горутина» — goroutine, тогда как вопрос об этом не говорит.
//
// Понятий берётся не больше max (0 — три): дальше идут случайные попутчики
// вопроса, и запрос размывается.
func ExpandQuery(question string, ents []FoundEntity, max int) string {
	if len(ents) == 0 {
		return question
	}
	if max <= 0 {
		max = 3
	}
	var b strings.Builder
	b.WriteString(question)

	// То, что в вопросе уже есть, второй раз не пишется.
	//
	// Замер 30.08.2026, первая редакция этой правки: на вопрос «горутина»
	// граф давал понятие с тем же именем, слово удваивалось в запросе, вес
	// русского написания рос вдвое — и правка, задуманная ради английских книг,
	// работала против них. Повтор помогает только тому написанию, которое
	// и так совпало.
	have := " " + strings.ToLower(question) + " "
	add := func(word string) {
		w := strings.ToLower(strings.TrimSpace(word))
		if w == "" || strings.Contains(have, " "+w+" ") {
			return
		}
		have += w + " "
		b.WriteString(" ")
		b.WriteString(word)
	}

	for i, e := range ents {
		if i >= max {
			break
		}
		add(e.Name)
		// Безопасный список: синоним, который является именем другого понятия,
		// подмешал бы в запрос к книгам чужой термин («goroutine, он же Go»
		// вытянул бы книги про язык).
		for _, al := range e.AliasesSafe {
			add(al)
		}
	}
	return b.String()
}
