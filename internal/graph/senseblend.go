package graph

import (
	"math/rand"
	"sort"
)

// Подмешивание смысла в вес связи.
//
// **Зачем.** Разбиение считает модулярность, а она видит **только вес связи**.
// Для неё «LLM → эмбеддинг» и «LLM → Notion» — одно и то же, если веса равны.
// Отсюда слипание вокруг узлов-концентраторов: со словом «LLM» в одном куске
// стоит всё подряд, связи набираются одинаковые, и Louvain честно сваливает
// это в одну тему. Замер 06.09.2026 показал, что ручка γ до этой беды
// не достаёт: у тем от ста понятий смысловой зазор 0.022–0.027 против 0.058
// у обычных при **любом** γ от 1 до 12 — дробление ограничивает размер темы,
// но не делает её однороднее.
//
// Векторы понятий эти два ребра различают уверенно, посчитаны заранее и лежат
// на диске. Подмешать их в вес — единственный способ дать разбиению сигнал,
// которого в связях нет.
//
// **Почему близость считается от фона, а не сама по себе.** У bge-m3 два
// случайных имени понятий похожи на 0.410 (замер 06.09.2026) — эмбеддинги
// коротких строк не центрированы. Множитель `1 + β·cos` при таком фоне почти
// не различает рёбра: 1.7 против 1.3 у пары «явно про одно» и «явно про разное».
// Поэтому берётся отклонение от фона: `1 + β·(cos − фон)`. Тогда связь по смыслу
// усиливается, связь мимо смысла — ослабляется, и при β = 2 разница между теми же
// рёбрами уже двукратная.
//
// **Фон меряется, а не назначается.** Он зависит от модели эмбеддингов и от
// состава библиотеки, и зашитая константа устарела бы на первой же смене
// модели. Считается выборкой случайных пар понятий с постоянным зерном.
//
// **Вес не уходит в ноль и не становится отрицательным.** Отрицательный вес
// ломает модулярность: сумма весов в знаменателе перестаёт быть нормировкой.
// Поэтому множитель снизу ограничен senseMinFactor. Ребро, по смыслу совсем
// чужое, становится слабым, но не исчезает: убирать связь, которую извлекла
// модель, на основании близости имён — это уже не подсказка, а подмена данных.
//
// **Понятия без вектора связь не меняют.** Их 11% (замер 06.09.2026), и молча
// обнулять или усиливать их связи значило бы подмешать в разбиение не смысл,
// а возраст понятия: вектор есть у тех, кто попал в граф раньше.

const (
	// senseMinFactor — нижняя граница множителя веса.
	senseMinFactor = 0.05

	// senseBackgroundPairs — сколько случайных пар брать на замер фона.
	// Двадцати тысяч хватает: разброс среднего на таком числе — третий знак,
	// а множитель считается по разнице во втором.
	senseBackgroundPairs = 20000
)

// SenseBlend — что дало подмешивание смысла в веса связей.
type SenseBlend struct {
	// Ready — считалось ли подмешивание вообще (нужны векторы и β > 0).
	Ready bool

	Beta float64

	// Background — измеренная близость случайной пары понятий.
	Background float64

	// Edges — рёбер просмотрено, Blended — у скольких вес изменён,
	// NoVector — у скольких вектора не нашлось хотя бы у одного конца.
	Edges, Blended, NoVector int

	// Weakened — сколько рёбер ослаблено (близость ниже фона). Число важно
	// само по себе: если ослаблено почти всё, фон замерен неверно.
	Weakened int
}

// blendBySense правит веса связей по близости векторов понятий.
//
// Правит **на месте**: adj строится под каждое разбиение заново, копия ради
// чистоты стоила бы сотен мегабайт на живом графе.
func (g *Graph) blendBySense(adj map[uint32]map[uint32]float64, beta float64) SenseBlend {
	st := SenseBlend{Beta: beta}
	if g == nil || beta <= 0 || g.vecs == nil || !g.vecs.Ready() {
		return st
	}
	v := g.vecs
	st.Background = backgroundCosine(v, adjIDs(adj))
	st.Ready = true

	for a, row := range adj {
		for b := range row {
			// Каждая пара считается один раз: adj хранит обе стороны, и вторая
			// правится тем же множителем — иначе граф перестанет быть
			// неориентированным, а Louvain на это не рассчитан.
			if a >= b {
				continue
			}
			st.Edges++
			c, ok := v.cosine(a, b)
			if !ok {
				st.NoVector++
				continue
			}
			f := 1 + beta*(c-st.Background)
			if f < senseMinFactor {
				f = senseMinFactor
			}
			if f < 1 {
				st.Weakened++
			}
			adj[a][b] *= f
			adj[b][a] *= f
			st.Blended++
		}
	}
	return st
}

// adjIDs — понятия графа связей, по возрастанию: порядок нужен, чтобы выборка
// фона не зависела от обхода карты.
func adjIDs(adj map[uint32]map[uint32]float64) []uint32 {
	ids := make([]uint32, 0, len(adj))
	for id := range adj {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	return ids
}

// backgroundCosine — близость случайной пары понятий: уровень «просто два
// понятия одной библиотеки», от которого и отсчитывается смысл.
func backgroundCosine(v *EntityVectors, ids []uint32) float64 {
	if len(ids) < 2 {
		return 0
	}
	rnd := rand.New(rand.NewSource(cosSeed))
	var sum float64
	var n int
	for k := 0; k < 2*senseBackgroundPairs && n < senseBackgroundPairs; k++ {
		a, b := ids[rnd.Intn(len(ids))], ids[rnd.Intn(len(ids))]
		if a == b {
			continue
		}
		if c, ok := v.cosine(a, b); ok {
			sum += c
			n++
		}
	}
	if n == 0 {
		return 0
	}
	return sum / float64(n)
}
