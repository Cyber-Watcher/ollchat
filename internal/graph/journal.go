package graph

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
)

// Оборванный хвост журнала и дозапись после него.
//
// **Беда.** Журналы графа читаются до последней целой записи: хвост короче
// записи отбрасывается, и всё, что до него, годится. Но тот же файл затем
// открывается на дозапись (O_APPEND), и до 07.10.2026 обрывок в нём оставался:
// первая же новая запись ложилась ПОСЛЕ обрывка. В двоичном журнале (упоминания,
// связи, отметки, синонимы формата 2) от этого всё дописанное читалось со
// сдвигом — мусорные номера понятий и кусков; в реестре понятий первая новая
// строка склеивалась с обрывком и пропадала (аудит 07.10.2026, №3,
// воспроизведено: «сущность №9», синоним {Entity:2 Chunk:327681#131072}).
//
// Обрывок оставляет почти любой жёсткий обрыв сборки — kill -9, OOM, питание:
// буфер записи не кратен длине записи (65536 % 12 = 4, 65536 % 24 = 16),
// и автоматический сброс буфера режет запись пополам. Мягкая остановка (Ctrl+C)
// сбрасывает всё и обрывка не оставляет.
//
// **Решение.** Перед ПЕРВОЙ дозаписью хвост приводится в порядок: двоичный
// журнал срезается до целого числа записей, реестр понятий — до последнего
// перевода строки. Так же поступает дозапись векторов (vecappend.go). Запись
// реестра, которой недостаёт одного перевода строки, не срезается: она цела
// и читается — ей дописывается перевод строки.
//
// **Только писатель.** Читатели (служба, диалог, приборы) журналы не правят:
// обрывок посреди идущей сборки — это её же запись, которую она допишет
// следующим сбросом буфера, и срез под ней сдвинул бы всё дальнейшее. Хвост
// правит тот, кто будет писать: сборка под замком (Lock, OpenForBuild), а в
// остальных случаях — первая запись. Перед правкой сверяется, что файл тот же
// и не вырос с чтения: иначе срез снёс бы чужие записи, а дозапись по
// устаревшему состоянию в памяти выдала бы уже выданные номера понятий.

// ErrStale — журнал на диске уже не тот, что был прочитан при открытии графа:
// его подменила чистка или дописал другой процесс. Дописывать в такой граф
// нельзя: записи ушли бы в подменённый файл или легли бы поверх чужих. Граф
// надо открыть заново.
var ErrStale = errors.New("граф изменился после открытия")

// journalTail — что нашлось в конце журнала при чтении и что с этим сделано.
type journalTail struct {
	read    int64 // байт прочитано при открытии: целые записи и обрывок
	whole   int64 // из них — целые записи
	newline bool  // реестр: последняя строка цела, недописан лишь перевод строки
	ready   bool  // хвост приведён в порядок, дозапись разрешена
	note    string
}

// record — учёт целой записи при чтении.
func (t *journalTail) record(n int) {
	t.read += int64(n)
	t.whole += int64(n)
}

// torn — учёт обрывка в конце файла при чтении.
func (t *journalTail) torn(n int) { t.read += int64(n) }

// prepare приводит хвост журнала в порядок перед первой дозаписью через f.
// Зовётся под замком журнала; повторный вызов ничего не делает.
func (t *journalTail) prepare(f *os.File, path string) error {
	if t.ready {
		return nil
	}
	name := filepath.Base(path)
	if f == nil {
		return fmt.Errorf("%s: журнал не открыт на запись", name)
	}
	have, err := f.Stat()
	if err != nil {
		return err
	}
	// Тот ли это файл, что читался: чистка и уплотнение подменяют журналы
	// переименованием, и дескриптор, открытый до подмены, пишет в копию «.bak-…».
	now, err := os.Stat(path)
	if err != nil || !os.SameFile(have, now) {
		return fmt.Errorf("%w: %s подменён на диске (чистка, уплотнение или перенос номеров книг) — "+
			"откройте граф заново", ErrStale, name)
	}
	if size := have.Size(); size != t.read {
		return fmt.Errorf("%w: в %s при открытии было %d байт, теперь %d — его дописал другой процесс; "+
			"откройте граф заново", ErrStale, name, t.read, size)
	}
	switch {
	case t.newline:
		if _, err := f.Write([]byte{'\n'}); err != nil {
			return err
		}
		t.note = name + ": последней записи недоставало перевода строки — дописан"
	case t.whole < t.read:
		if err := f.Truncate(t.whole); err != nil {
			return err
		}
		t.note = fmt.Sprintf("%s: срезан оборванный хвост, %d байт (обрыв прошлой записи)", name, t.read-t.whole)
	default:
		t.ready = true
		return nil
	}
	// Срез — на диск сразу: без него сбой питания мог бы вернуть обрывок
	// под уже дописанные следом записи.
	if err := f.Sync(); err != nil {
		return err
	}
	t.ready = true
	return nil
}
