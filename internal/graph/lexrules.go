package graph

// Правила словесного входа: насколько смелой может быть догадка по слову.
//
// Оба числа добыты замером 03.09.2026 на наборе `graph_relations.toml`
// (60 вопросов, инструмент `ollchat --graph-entry-eval`) и вынесены в настройки,
// потому что зависят от библиотеки: у собрания в двести книг и у собрания в две
// тысячи «две книги» значат разное.
//
// С этапа 91 (R3) действующие значения живут в Rules открытого графа,
// а здесь остались только умолчания с их обоснованием.

const (
	// DefaultStemMinLen — короче этого основа слова ключом поиска не станет.
	//
	// Замер: понятие «ИИ» лежало в указателе основ под ключом «и»
	// (`StemPhrase("ии") == "и"`), и союз «и» из вопроса находил его
	// в 60 случаях из 60 — в каждом русском вопросе.
	DefaultStemMinLen = 3

	// DefaultStemMinBooks — сколько книг должно знать понятие, чтобы оно
	// годилось в ответ на совпадение по ОСНОВЕ слова.
	//
	// Замер: «Связанность» (6 упоминаний в одной книге) приходила в 59 вопросов
	// из 60, потому что «связаны» совпадает с ней основой. Частота слова тут
	// не помогает: «связаны» встречается в 1.0% кусков, «goroutine» — в 1.1%.
	// Точного совпадения по имени правило не касается вовсе.
	DefaultStemMinBooks = 2
)

const (
	// DefaultSenseTie — ступень огрубления смысловой близости. Всё, что попало
	// в одну ступень, считается одинаково близким, и выбор внутри неё решает
	// распространённость понятия. Замер 26.08.2026: разброс между главным
	// понятием и его частными написаниями был около трёх сотых.
	DefaultSenseTie = 0.05

	// DefaultSenseMargin — насколько понятие должно быть выше середины верхушки,
	// чтобы попасть в смысловой вход. Порог относительный: абсолютный тут
	// не работает — у чужой пары близость 0.565, у своей 0.576 (замер 26.08.2026).
	DefaultSenseMargin = 0.03

	// DefaultVectorAliases — сколько синонимов уходит в вектор понятия вместе
	// с именем. Длинный хвост размывает вектор; мусорный синоним в первых
	// строках его отравляет (замер 03.09.2026: у «Guard» это слово «защита»).
	DefaultVectorAliases = 4

	// DefaultMaxEvidences — сколько кусков-подтверждений показывать у одной связи.
	DefaultMaxEvidences = 4
)
