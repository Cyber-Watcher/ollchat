package graph

import (
	"regexp"
	"strings"
	"unicode"
)

// Привратник: стоит ли вообще искать по графу.
//
// Связывание вопроса с понятиями отвечает на вопрос «есть ли такие слова
// в графе», а не «спрашивают ли про книги». Разница видна на живом графе
// по книгам об ИИ (замер 23.08.2026, 14 тыс. разобранных кусков):
//
//	«почему тест падает на строке 42»  → понятие «тест» (33 упоминания в 10 книгах)
//	«сделай коммит и запушь»           → понятие «коммит» (3 упоминания в 2 книгах)
//
// Оба вопроса про здешний код, и карта понятий из книг им не нужна — а по
// словам они связываются не хуже настоящих. Отличает их не словарь, а форма:
// это распоряжения о рабочем каталоге, а не вопросы о предмете. Поэтому перед
// связыванием стоит дешёвый запрет по признакам работы с кодом.
//
// Запрет намеренно узкий. Пропустить лишний вопрос к графу стоит две сотни
// токенов, а не пропустить нужный — стоит ответа не по книгам, и человек об
// этом даже не узнает. Поэтому «объясни», «расскажи», «покажи» и «напиши»
// в списке не значатся: они одинаково часто начинают и просьбу к коду,
// и вопрос по предмету.

// workVerbs — распоряжения о рабочем каталоге. Основы без окончаний: приставки
// и вид глагола меняются, корень нет.
var workVerbs = []string{
	"перепиш", "переписать",
	"исправ", "почин", "поправ", "доработ",
	"отрефактор", "зарефактор", "рефактор",
	"закоммить", "закоммить", "коммитн", "запуш", "запушь",
	"собери", "собрать", "скомпилир", "запусти", "запустить", "перезапусти",
	"удали", "удалить", "убери", "убрать", "замени", "заменить",
	"переименуй", "переименовать", "вынеси", "вынести",
	"отформатируй", "форматируй",
	"добавь", "добавить", "внеси", "внести",
	"почисти", "почистить",
}

// workMarkers — следы рабочего каталога в самом тексте вопроса.
var (
	// Путь или имя файла с расширением: main.go, ./cmd/ollchat, internal/ui.
	reFileish = regexp.MustCompile(`(?i)[\w./-]+\.(go|py|js|ts|tsx|rs|cs|java|c|h|cpp|sh|toml|yaml|yml|json|md|sql|tf)\b|(^|\s)\.?/[\w./-]+`)
	// Ссылка на строку: «на строке 42», «line 42», «:42:».
	reLineRef = regexp.MustCompile(`(?i)стро[кч][аеиу]?\s*№?\s*\d+|line\s+\d+|:\d+:\d*`)
	// Вывод команд и трассировки: их приносят целиком, вместе с вопросом.
	reTrace = regexp.MustCompile(`(?i)panic:|traceback|stack trace|exit status \d|go build|npm (run|install)|git (commit|push|diff|status)`)
)

// Граница слова здесь не `\b`: в RE2 это граница ASCII-слова, а после «привет»
// её нет вовсе — буква «т» для него не буква. Отсюда явная проверка «конец
// строки либо не-буква».
//
// reSmallTalk — вопросы не о предмете вовсе: время, приветствия, вопросы
// к самому собеседнику. Замер на живом графе 24.08.2026: «какой сейчас год
// и какое сегодня число» связался с понятием «число» (14 упоминаний в 5 книгах)
// и получил карту понятий на 319 токенов ни за что.
//
// Список короткий и точный по той же причине, что и список глаголов работы:
// пропустить лишний вопрос к графу стоит две сотни токенов, а не пропустить
// нужный — стоит ответа не по книгам.
var reSmallTalk = regexp.MustCompile(`(?i)^\s*(привет|здравствуй|добрый (день|вечер|утро)|доброе утро|` +
	`спасибо|благодарю|пока|до свидания|ок|окей|ясно|понятно|хорошо|` +
	`как дела|как ты|кто ты|как тебя зовут|что ты умеешь|что умеешь|` +
	`какой (сейчас |нынче )?год|како[ей] (сегодня |сейчас )?(число|день|дата)|` +
	`который час|сколько (сейчас )?времени)(?:$|[^\p{L}])`)

// WorkRequest сообщает, что вопрос не к библиотеке: он либо про здешний код,
// либо вовсе не о предмете — время, приветствие, вопрос к собеседнику.
//
// Проверка местная и стоит микросекунды: она делается перед каждым вопросом,
// включая «спасибо».
func WorkRequest(q string) bool {
	s := strings.ToLower(strings.TrimSpace(q))
	if s == "" {
		return true
	}
	if reSmallTalk.MatchString(s) {
		return true
	}
	// Блок кода в вопросе — разговор про этот код, а не про книги.
	if strings.Contains(s, "```") {
		return true
	}
	if reFileish.MatchString(s) || reLineRef.MatchString(s) || reTrace.MatchString(s) {
		return true
	}
	for _, w := range strings.FieldsFunc(s, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	}) {
		for _, v := range workVerbs {
			if strings.HasPrefix(w, v) {
				return true
			}
		}
	}
	return false
}
