package graph

import (
	"math/rand"
	"sort"
)

// Смысловая связность тем: насколько понятия одной темы близки друг другу
// по векторам — и насколько это больше, чем у случайной пары понятий графа.
//
// **Зачем.** Разбиение считает модулярность, а она видит **только вес связи**.
// Для неё связь «LLM → эмбеддинг» и «LLM → Notion» одинаковы, если веса равны,
// и потому крупная тема-каша по числам выглядит как настоящая тема: замер
// 26.08.2026 дал «тему» из 3 662 понятий, где свалено всё подряд, и отличить
// её от темы удалось только глазами. Векторы понятий эти два случая различают
// уверенно, лежат на диске готовыми и не требуют ни модели, ни видеокарты.
//
// **Почему «внутри» без «снаружи» — не мера.** Тема из чистых синонимов даст
// близость 0.95 и будет выглядеть отличной, а тема из пяти разных, но соседних
// понятий — 0.6 и будет выглядеть хуже, хотя она-то и есть тема. Судить надо
// по **зазору**: насколько понятия темы ближе друг к другу, чем к случайному
// понятию графа. У каши зазор около нуля — её участники похожи друг на друга
// ровно настолько же, насколько на постороннее понятие.
//
// **Почему медиана, а не среднее.** Тем десятки тысяч, и распределение у них
// не симметричное: пара сотен тем-концентраторов утянула бы среднее. Медиана
// отвечает на вопрос «как выглядит обычная тема», а он тут и нужен. Тем же
// соображением считается срединная связность в `medianCohesion`.
//
// **Почему порог в пять понятий.** Пятёрка уже принята в этом пакете за
// границу «годится в тему» (см. DefaultResolution): по числу тем от пяти
// понятий подбиралось γ. Мера, считающая по другой границе, была бы
// несравнима с тем подбором.
//
// **Почему выборка пар, а не все.** Тема на 200 понятий даёт 19 900 пар,
// а тем — десятки тысяч. Выборка фиксированного размера превращает счёт
// из квадратичного в линейный по числу тем. Зерно **постоянное**: разбиение
// в этом пакете детерминировано намеренно (см. community.go), и мера,
// которая от запуска к запуску даёт разные числа, обесценила бы это свойство.
//
// **Чего мера не говорит.** Она не отличает верную тему от неверной — только
// связную от бессвязной. Тема из пяти понятий про Kubernetes, названная
// «Хранилища данных», получит отличный зазор.

const (
	// CosMinMembers — тема мельче в счёт не идёт: у пары понятий близость
	// говорит о паре, а не о теме.
	CosMinMembers = 5

	// cosPairsPerTheme — сколько пар брать на тему с каждой стороны.
	cosPairsPerTheme = 50

	// CosBigMembers — с какого размера тема считается крупной и попадает
	// в отдельный счёт хвоста. Половина предела MaxSize (200 по умолчанию):
	// тема такого размера уже не читается как одна мысль.
	CosBigMembers = 100

	// cosSeed — постоянное зерно выборки: см. пояснение выше.
	cosSeed = 20260906
)

// ThemeCosine — смысловая связность разбиения.
type ThemeCosine struct {
	// Themes — по скольким темам посчитано (не сколько их всего).
	Themes int

	// In — медиана средней близости пар внутри темы.
	In float64

	// Out — медиана средней близости пар «понятие темы — постороннее понятие».
	Out float64

	// Gap — In минус Out. Это и есть мера: насколько тема плотнее фона.
	Gap float64

	// Covered — доля понятий уровня 0, у которых вектор посчитан.
	//
	// Отдельное поле, а не молчание: векторы считаются реже, чем растёт граф,
	// и у свежих понятий их нет. Тема, целиком собранная из новых понятий,
	// в счёт не попадает вовсе, и знать об этом надо, иначе число читается
	// как приговор разбиению, а означает «нечем судить».
	Covered float64

	// Big — по скольким крупным темам (от CosBigMembers понятий) посчитано,
	// и каков зазор у них.
	//
	// **Зачем отдельно от Gap.** Медиана по всем темам отвечает на вопрос «как
	// выглядит обычная тема», а обычная тема мелкая: при любом γ срединный
	// размер темы — два-три понятия, и такие темы связны всегда. Каша же живёт
	// в хвосте: замер 06.09.2026 при γ = 1 дал 28 383 темы, из которых крупнее
	// нормы 24 — и вот в них-то «Kubernetes, kubectl, KinD» соседствует со всем
	// подряд. Медиана этих двух десятков не видит вовсе. Поэтому хвост меряется
	// своим числом, а не растворяется в общем.
	Big    int
	GapBig float64

	// Pairs — сколько пар с каждой стороны брали на тему.
	Pairs int
}

// Ready сообщает, есть ли чем судить.
func (t ThemeCosine) Ready() bool { return t.Themes > 0 }

// ThemeCosineOf считает смысловую связность разбиения.
//
// Ничего не сохраняет и видеокарты не требует: читает готовые векторы понятий
// с диска. Нет векторов — возвращается пустое значение, а не ноль-как-ответ.
func (g *Graph) ThemeCosineOf(c *Communities, pairs int) ThemeCosine {
	if g == nil || c == nil || g.vecs == nil || !g.vecs.Ready() {
		return ThemeCosine{}
	}
	if pairs <= 0 {
		pairs = cosPairsPerTheme
	}
	v := g.vecs

	// Темы обходятся по возрастанию номера: порядок обхода влияет на выборку,
	// а выборка обязана быть повторяемой.
	lvl0 := c.Level(0)
	sort.Slice(lvl0, func(i, j int) bool { return lvl0[i].ID < lvl0[j].ID })

	// Понятия, у которых вектор есть, — по темам и одним списком для фона.
	var (
		members int
		all     []uint32
		owner   = map[uint32]int{}
		vecMem  = make([][]uint32, len(lvl0))
	)
	for i, com := range lvl0 {
		for _, m := range com.Members {
			members++
			if _, ok := v.vectorOf(m); !ok {
				continue
			}
			vecMem[i] = append(vecMem[i], m)
			all = append(all, m)
			owner[m] = com.ID
		}
	}
	out := ThemeCosine{Pairs: pairs}
	if members > 0 {
		out.Covered = float64(len(all)) / float64(members)
	}
	if len(all) < 2 {
		return out
	}

	rnd := rand.New(rand.NewSource(cosSeed))
	var ins, outs, gapsBig []float64
	for i := range lvl0 {
		mem := vecMem[i]
		if len(mem) < CosMinMembers {
			continue
		}
		in, okIn := meanInsidePairs(v, mem, pairs, rnd)
		if !okIn {
			continue
		}
		ex, okOut := meanOutsidePairs(v, mem, all, owner, lvl0[i].ID, pairs, rnd)
		if !okOut {
			continue
		}
		ins = append(ins, in)
		outs = append(outs, ex)
		// Размер берётся по всей теме, а не по её понятиям с векторами: крупной
		// её делает состав, а не то, чего мы успели посчитать.
		if len(lvl0[i].Members) >= CosBigMembers {
			gapsBig = append(gapsBig, in-ex)
		}
	}
	if len(ins) == 0 {
		return out
	}
	out.Themes = len(ins)
	out.In = median(ins)
	out.Out = median(outs)
	out.Gap = out.In - out.Out
	out.Big = len(gapsBig)
	out.GapBig = median(gapsBig)
	return out
}

// ShuffledLevel0 — то же разбиение с перемешанным составом: темы прежних
// размеров, набранные случайными понятиями.
//
// **Зачем.** Мера без нулевой гипотезы не читается. Зазор 0.058 — это много
// или мало? Ответ даёт только сравнение с разбиением, в котором смысла нет
// заведомо: если случайное даёт столько же, мера ничего не меряет, и никакие
// выводы по ней делать нельзя. Размеры тем сохраняются, потому что зазор
// зависит от размера темы, и сравнивать надо с поправкой на него.
//
// Перемешивание детерминировано тем же зерном, что и выборка пар.
func ShuffledLevel0(c *Communities) *Communities {
	if c == nil {
		return nil
	}
	lvl0 := c.Level(0)
	sort.Slice(lvl0, func(i, j int) bool { return lvl0[i].ID < lvl0[j].ID })

	pool := make([]uint32, 0)
	for _, com := range lvl0 {
		pool = append(pool, com.Members...)
	}
	rnd := rand.New(rand.NewSource(cosSeed))
	rnd.Shuffle(len(pool), func(i, j int) { pool[i], pool[j] = pool[j], pool[i] })

	out := &Communities{Entities: c.Entities, Edges: c.Edges}
	var from int
	for _, com := range lvl0 {
		n := len(com.Members)
		out.List = append(out.List, Community{
			ID: com.ID, Level: 0, Parent: com.Parent,
			Members: pool[from : from+n],
		})
		from += n
	}
	return out
}

// meanInsidePairs — средняя близость пар внутри темы.
//
// Пар мало — берутся все: выборка из десяти пар случайными десятью бросками
// пропустила бы часть и повторила бы часть, а стоит перебор столько же.
func meanInsidePairs(v *EntityVectors, mem []uint32, pairs int, rnd *rand.Rand) (float64, bool) {
	total := len(mem) * (len(mem) - 1) / 2
	var sum float64
	var n int
	if total <= pairs {
		for i := 0; i < len(mem); i++ {
			for j := i + 1; j < len(mem); j++ {
				if c, ok := v.cosine(mem[i], mem[j]); ok {
					sum += c
					n++
				}
			}
		}
	} else {
		for k := 0; k < pairs; k++ {
			i := rnd.Intn(len(mem))
			j := rnd.Intn(len(mem))
			if i == j {
				continue
			}
			if c, ok := v.cosine(mem[i], mem[j]); ok {
				sum += c
				n++
			}
		}
	}
	if n == 0 {
		return 0, false
	}
	return sum / float64(n), true
}

// meanOutsidePairs — средняя близость понятий темы к посторонним понятиям.
//
// Постороннее берётся из всего графа, а не из соседней темы: нужен **фон**,
// уровень «просто два понятия одной библиотеки». Ближайшая соседняя тема
// дала бы более строгую меру (силуэт), но искать её значит сравнивать каждую
// тему с каждой — на десятках тысяч тем это дороже всего остального счёта.
//
// Фона может не оказаться вовсе: если понятия с векторами лежат в одной теме,
// сравнивать не с чем. Тогда возвращается «не посчитано», и тема выпадает
// из счёта целиком — вместе со своим «внутри». Ополовиненная мера («внутри»
// без фона) хуже отсутствующей: её прочитают как ответ.
func meanOutsidePairs(v *EntityVectors, mem, all []uint32, owner map[uint32]int,
	id, pairs int, rnd *rand.Rand) (float64, bool) {

	var sum float64
	var n int
	// Попыток вдвое больше, чем нужно пар: жребий иногда выпадает на своё же
	// понятие, и без запаса тема с большой долей графа внутри недобрала бы.
	for k := 0; k < 2*pairs && n < pairs; k++ {
		a := mem[rnd.Intn(len(mem))]
		b := all[rnd.Intn(len(all))]
		if owner[b] == id {
			continue
		}
		if c, ok := v.cosine(a, b); ok {
			sum += c
			n++
		}
	}
	if n == 0 {
		return 0, false
	}
	return sum / float64(n), true
}

// median — срединное значение; вход портится сортировкой, и это намеренно:
// копия ради чистоты на десятках тысяч тем стоила бы больше, чем весит польза.
//
// При чётном числе значений берётся **верхнее** из двух срединных, без
// усреднения — так же, как в medianCohesion. На десятках тысяч тем разницы нет,
// а на двух-трёх мера превращается в максимум: 06.09.2026 на этом споткнулся
// тест из двух тем, показавший «зазор случайного разбиения 0.22».
func median(xs []float64) float64 {
	if len(xs) == 0 {
		return 0
	}
	sort.Float64s(xs)
	return xs[len(xs)/2]
}
