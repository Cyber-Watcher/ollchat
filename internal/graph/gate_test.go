package graph

import "testing"

// TestWorkRequest — что привратник обязан отсечь и что обязан пропустить.
//
// Примеры не выдуманы: первые четыре взяты из замера на живом графе по книгам
// об ИИ, где каждый из них связался с понятием из книг и получил бы карту
// понятий ни за что.
func TestWorkRequest(t *testing.T) {
	work := []string{
		"сделай коммит и запушь",
		"почему тест падает на строке 42",
		"перепиши эту функцию покороче",
		"почини сборку, go build падает",
		"добавь в internal/ui обработку Ctrl+G",
		"исправь main.go",
		"удали лишний импорт",
		"запусти тесты ещё раз",
		"вот код:\n```go\nfunc main() {}\n```\nчто не так",
		"panic: runtime error: index out of range",
	}
	for _, q := range work {
		if !WorkRequest(q) {
			t.Errorf("не отсечено распоряжение о коде: %q", q)
		}
	}

	// Вопросы не о предмете вовсе: время, приветствия, вопросы к собеседнику.
	// Первый взят с живой проверки — он цеплялся за понятие «число».
	smallTalk := []string{
		"какой сейчас год и какое сегодня число",
		"какое сегодня число",
		"который час",
		"привет",
		"спасибо, это то что нужно",
		"как дела",
		"что ты умеешь",
	}
	for _, q := range smallTalk {
		if !WorkRequest(q) {
			t.Errorf("не отсечён вопрос не о предмете: %q", q)
		}
	}

	knowledge := []string{
		"что такое квантование",
		"расскажи про RAG своими словами",
		"как связаны LoRA и дообучение",
		"объясни, что такое градиентный спуск",
		"как выбрать размер контекстного окна",
		"чем attention отличается от рекуррентных сетей",
		"что библиотека говорит про векторные базы",
		"покажи, как обычно объясняют обратное распространение",
		"напиши краткий обзор способов сжатия моделей",
		"расскажи про Kubernetes",
		"что такое год в контексте временных рядов",
	}
	for _, q := range knowledge {
		if WorkRequest(q) {
			t.Errorf("отсечён вопрос по предмету: %q", q)
		}
	}
}
