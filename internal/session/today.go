package session

import (
	"fmt"
	"strings"
	"time"
)

// Сегодняшняя дата в системном сообщении.
//
// Модель не знает, какое сегодня число: в весах остался предел её обучения,
// и на вопрос «какой сейчас год» она называет год выпуска. Замечено владельцем
// на `deepseek-r1`: 2023-й вместо 2026-го. Ollama даты не подставляет, ollchat
// раньше тоже не подставлял — в системное сообщение уходило только то, что
// написано в настройках сервера.
//
// Дата ставится **при сборке каждого запроса**, а не при запуске: сеанс живёт
// сутками, и вчерашняя дата в контексте хуже её отсутствия. По той же причине
// она не пишется ни в `SetSystem`, ни в сохранённую сессию: сохранённый вчера
// разговор не должен утверждать, что сегодня вчера.
//
// Цена — около двух десятков токенов на запрос. Оговорка про предел знаний
// в ней важнее самой даты: без неё модель видит число, но продолжает считать
// своё представление о мире нынешним.

var months = [...]string{
	"января", "февраля", "марта", "апреля", "мая", "июня",
	"июля", "августа", "сентября", "октября", "ноября", "декабря",
}

// TodayLine — строка о сегодняшнем дне для системного сообщения.
func TodayLine(now time.Time) string {
	return fmt.Sprintf("Сегодня %d %s %d года. Эту дату бери отсюда, а не из памяти: "+
		"твои знания заканчиваются раньше, и с тех пор многое изменилось. "+
		"Где ответ зависит от времени — версии, цены, состав инструментов, «как принято» — "+
		"скажи, на какой момент ты его даёшь.",
		now.Day(), months[int(now.Month())-1], now.Year())
}

// SetToday включает или выключает подстановку даты в системное сообщение.
func (c *Conversation) SetToday(on bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.today = on
}

// Today сообщает, подставляется ли дата.
func (c *Conversation) Today() bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.today
}

// systemFor собирает системное сообщение на указанный момент: сперва дата,
// затем то, что задал пользователь. Порядок такой потому, что настройка
// пользователя — главное, и обрывать её служебной припиской посередине нельзя.
func (c *Conversation) systemFor(now time.Time) string {
	parts := make([]string, 0, 2)
	if c.today {
		parts = append(parts, TodayLine(now))
	}
	if s := strings.TrimSpace(c.system); s != "" {
		parts = append(parts, s)
	}
	return strings.Join(parts, "\n\n")
}
