#!/usr/bin/env bash
# Возврат Ollama в общий доступ. Запускается таймером раз в четверть часа
# и сам решает, пора ли.
#
# Правило: сервер остаётся закрытым, только пока идёт живой прогон внутри
# своего окна. Всё остальное — повод открыть:
#   • окно кончилось (утро буднего дня, конец выходного промежутка);
#   • прогон умер посреди окна (отметка о нём протухла) — иначе стенд
#     простоял бы закрытым до конца суток субботы.
set -uo pipefail

LOG="$(olleval config --get root)/logs/restore.log"
mkdir -p "$(dirname "$LOG")"
say() { echo "$(date '+%F %H:%M:%S %Z')  $*" | tee -a "$LOG"; }

# Сервер не закрыт прогоном — делать нечего и писать не о чем. Без этой
# проверки журнал набирал бы по строке каждые четверть часа, и настоящие
# события (кто и когда открыл сервер) тонули бы в сотне «уже открыт».
# Спрашивается сам скрипт изоляции, а не адрес: сервер, который и до прогона
# слушал только localhost, иначе «открывался» бы каждый тик.
if ! olleval-isolate.sh is-on; then
  exit 0
fi

if olleval window --quiet; then
  if olleval running --quiet; then
    exit 0   # окно идёт, прогон жив, сервер закрыт — так и должно быть
  fi
  say "окно идёт, но живого прогона нет — открываю сервер"
else
  say "окно кончилось — открываю сервер"
fi

olleval-isolate.sh off 2>&1 | tee -a "$LOG"
